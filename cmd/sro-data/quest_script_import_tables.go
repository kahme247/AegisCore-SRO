package main

import "context"

func clearVSROQuestScriptTables(ctx context.Context, execute func(context.Context, string) error) error {
	for _, statement := range [...]string{
		"DELETE FROM `REF_QUEST_SCRIPT_REWARD_ITEM`",
		"DELETE FROM `REF_QUEST_SCRIPT_REWARD`",
		"DELETE FROM `REF_QUEST_DELIVER_ITEM_ENTRY`",
		"DELETE FROM `REF_QUEST_DELIVER_ITEM`",
		"DELETE FROM `REF_QUEST_DIALOG_OBJECTIVE`",
		"DELETE FROM `REF_QUEST_KILL_PLAYER_JOB_STATE`",
		"DELETE FROM `REF_QUEST_KILL_PLAYER_OBJECTIVE`",
		"DELETE FROM `REF_QUEST_COLLECTION_ITEM_SOURCE`",
		"DELETE FROM `REF_QUEST_COLLECTION_ITEM_OBJECTIVE`",
		"DELETE FROM `REF_QUEST_EXTENDED_KILL_TARGET`",
		"DELETE FROM `REF_QUEST_EXTENDED_KILL_OBJECTIVE`",
		"DELETE FROM `REF_QUEST_TALISMAN_OBJECTIVE`",
		"DELETE FROM `REF_QUEST_DEPENDENCY_ENTRY`",
		"DELETE FROM `REF_QUEST_DEPENDENCY_GROUP`",
		"DELETE FROM `REF_QUEST_START_NPC`",
		"DELETE FROM `REF_QUEST_START_METHOD`",
		"DELETE FROM `REF_QUEST_START_CONDITION`",
		"DELETE FROM `REF_QUEST_SCRIPT_POINT_REWARD`",
		"DELETE FROM `REF_QUEST_RACE_START_CONDITION`",
		"DELETE FROM `REF_QUEST_JOB_START_CONDITION`",
		"DELETE FROM `REF_QUEST_COMPLETION_POLICY`",
		"DELETE FROM `REF_QUEST_DELIVER_ITEM_EX`",
		"DELETE FROM `REF_QUEST_KILL_OBJECTIVE`",
		"DELETE FROM `REF_QUEST_SCRIPT_DECLARATION`",
	} {
		if err := execute(ctx, statement); err != nil {
			return err
		}
	}
	return nil
}

func questScriptRowsAffectedExactlyOnce(result interface {
	RowsAffected() (int64, error)
}) bool {
	affected, err := result.RowsAffected()
	return err == nil && affected == 1
}

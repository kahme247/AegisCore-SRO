package captures

import (
	"encoding/hex"
	"strings"
	"testing"
)

func TestDecodeFixtureAndReplayLogicalPayload(t *testing.T) {
	payload := []byte{0x0D, 0xEC, 0x08, 0x01}
	payloadHex := hex.EncodeToString(payload)
	fixture := validFixture(payloadHex)
	decoded, err := DecodeFixture([]byte(fixture))
	if err != nil {
		t.Fatal(err)
	}
	if err = Replay(decoded, func(_ Frame, got []byte) ([]byte, error) {
		return append([]byte(nil), got...), nil
	}); err != nil {
		t.Fatal(err)
	}
}

func TestDecodeFixtureRejectsUnknownFieldsAndLengthMismatch(t *testing.T) {
	valid := validFixture("0dec0801")
	unknown := strings.TrimSuffix(valid, "}") + `,"unexpected":true}`
	if _, err := DecodeFixture([]byte(unknown)); err == nil {
		t.Fatal("fixture with unknown field was accepted")
	}
	mismatch := strings.Replace(valid, `"logical_length":4`, `"logical_length":3`, 1)
	if _, err := DecodeFixture([]byte(mismatch)); err == nil {
		t.Fatal("fixture with mismatched logical length was accepted")
	}
	trailing := valid + "{}"
	if _, err := DecodeFixture([]byte(trailing)); err == nil {
		t.Fatal("fixture with trailing JSON was accepted")
	}
}

func TestReplayRejectsDifferentReEncoding(t *testing.T) {
	fixture, err := DecodeFixture([]byte(validFixture("0dec0801")))
	if err != nil {
		t.Fatal(err)
	}
	if err = Replay(fixture, func(_ Frame, _ []byte) ([]byte, error) {
		return []byte{0}, nil
	}); err == nil {
		t.Fatal("replay accepted different encoded payload")
	}
}


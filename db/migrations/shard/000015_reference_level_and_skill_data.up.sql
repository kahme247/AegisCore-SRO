-- Client-matched reference data is imported explicitly by `sro-data import-reference`.
-- Keeping the schema migration separate from the data import means a deployment never
-- silently changes progression or skill definitions at server startup.
CREATE TABLE `REF_LEVEL_DATA` (
    `LEVEL` SMALLINT UNSIGNED NOT NULL,
    `REQUIRED_EXPERIENCE` BIGINT UNSIGNED NOT NULL,
    `REQUIRED_SKILL_POINTS` INT UNSIGNED NOT NULL,
    `UNKNOWN_1` BIGINT NOT NULL,
    `UNKNOWN_2` BIGINT NOT NULL,
    `REQUIRED_JOB_EXPERIENCE` BIGINT NOT NULL,
    `REQUIRED_JOB_EXPERIENCE_2` BIGINT NOT NULL,
    `REQUIRED_JOB_EXPERIENCE_3` BIGINT NOT NULL,
    `RAW_FIELDS` JSON NOT NULL,
    PRIMARY KEY (`LEVEL`)
) ENGINE=InnoDB;

CREATE TABLE `REF_SKILL_DATA` (
    `ID` INT UNSIGNED NOT NULL,
    `SERVICE` TINYINT UNSIGNED NOT NULL,
    `GROUP_ID` INT UNSIGNED NOT NULL,
    `CODE_NAME` VARCHAR(128) NOT NULL,
    `NAME` TEXT NOT NULL,
    `GROUP_CODE_NAME` VARCHAR(128) NOT NULL,
    `BASE_SKILL_ID` INT UNSIGNED NOT NULL,
    `LEVEL` SMALLINT UNSIGNED NOT NULL,
    `TYPE` SMALLINT UNSIGNED NOT NULL,
    `NEXT_SKILL_ID` INT UNSIGNED NOT NULL,
    `INIT_TIME` INT UNSIGNED NOT NULL,
    `DELAY_TIME` INT NOT NULL,
    `NEXT_TIME` INT UNSIGNED NOT NULL,
    `COOLDOWN` INT UNSIGNED NOT NULL,
    `MASTERY_ID` INT UNSIGNED NOT NULL,
    `REQUIRED_MASTERY_LEVEL` SMALLINT UNSIGNED NOT NULL,
    `REQUIRED_SKILL_1_ID` INT UNSIGNED NOT NULL,
    `REQUIRED_SKILL_2_ID` INT UNSIGNED NOT NULL,
    `REQUIRED_SKILL_1_LEVEL` SMALLINT UNSIGNED NOT NULL,
    `REQUIRED_SKILL_2_LEVEL` SMALLINT UNSIGNED NOT NULL,
    `REQUIRED_SKILL_POINTS` INT UNSIGNED NOT NULL,
    `REQUIRED_RACE` SMALLINT UNSIGNED NOT NULL,
    `REQUIRED_WEAPON_1` SMALLINT UNSIGNED NOT NULL,
    `REQUIRED_WEAPON_2` SMALLINT UNSIGNED NOT NULL,
    `REQUIRED_MP` INT UNSIGNED NOT NULL,
    `MIN_HP_RATIO` SMALLINT UNSIGNED NOT NULL,
    `ICON` VARCHAR(255) NOT NULL,
    `RESOURCE_NAME` VARCHAR(255) NOT NULL,
    `DESCRIPTION` VARCHAR(255) NOT NULL,
    `STUDY_DESCRIPTION` VARCHAR(255) NOT NULL,
    `MAX_HP_RATIO` SMALLINT UNSIGNED NOT NULL,
    `EFFECTS` JSON NOT NULL,
    `RAW_FIELDS` JSON NOT NULL,
    PRIMARY KEY (`ID`),
    KEY `idx_ref_skill_group` (`GROUP_ID`),
    KEY `idx_ref_skill_mastery` (`MASTERY_ID`),
    KEY `idx_ref_skill_base_level` (`BASE_SKILL_ID`, `LEVEL`)
) ENGINE=InnoDB;

CREATE TABLE `FORTRESS` (
  `ID` tinyint unsigned NOT NULL,
  `CODE_NAME` varchar(64) NOT NULL,
  `FK_GUILD` int DEFAULT NULL,
  `TREASURY_GOLD` bigint unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UX_FORTRESS_CODE_NAME` (`CODE_NAME`),
  UNIQUE KEY `UX_FORTRESS_GUILD` (`FK_GUILD`),
  CONSTRAINT `FK_FORTRESS_GUILD` FOREIGN KEY (`FK_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;


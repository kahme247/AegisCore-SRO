CREATE TABLE `FORTRESS_EXPENDITURE` (
  `ID` bigint unsigned NOT NULL AUTO_INCREMENT,
  `FK_FORTRESS` tinyint unsigned NOT NULL,
  `FK_GUILD` int NOT NULL,
  `FK_CHAR` int DEFAULT NULL,
  `CHARACTER_NAME` varchar(64) NOT NULL,
  `AMOUNT` int unsigned NOT NULL,
  `REASON` tinyint unsigned NOT NULL,
  `CREATED_AT` datetime(6) NOT NULL,
  PRIMARY KEY (`ID`),
  KEY `IX_FORTRESS_EXPENDITURE_HISTORY` (`FK_FORTRESS`,`CREATED_AT`,`ID`),
  CONSTRAINT `CK_FORTRESS_EXPENDITURE_REASON` CHECK (`REASON` BETWEEN 0 AND 8),
  CONSTRAINT `FK_FORTRESS_EXPENDITURE_FORTRESS` FOREIGN KEY (`FK_FORTRESS`) REFERENCES `FORTRESS` (`ID`) ON DELETE CASCADE,
  CONSTRAINT `FK_FORTRESS_EXPENDITURE_GUILD` FOREIGN KEY (`FK_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE CASCADE,
  CONSTRAINT `FK_FORTRESS_EXPENDITURE_CHAR` FOREIGN KEY (`FK_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

ALTER TABLE `SRO_SHARD`.`CHAR`
    ALTER COLUMN `INVENTORY_SIZE` SET DEFAULT 45;

ALTER TABLE `SRO_SHARD`.`CHARACTER_CREATION_MODEL`
    ALTER COLUMN `INITIAL_INVENTORY_SIZE` SET DEFAULT 45;

UPDATE `SRO_SHARD`.`CHARACTER_CREATION_MODEL`
SET `INITIAL_INVENTORY_SIZE` = 45
WHERE `INITIAL_INVENTORY_SIZE` = 109;

UPDATE `SRO_SHARD`.`CHAR` AS c
SET c.`INVENTORY_SIZE` = 45
WHERE c.`INVENTORY_SIZE` = 109
  AND NOT EXISTS (
      SELECT 1
      FROM `SRO_SHARD`.`INVENTORY` AS inv
      WHERE inv.`FK_CHAR` = c.`id`
        AND inv.`SLOT` >= 45
  );

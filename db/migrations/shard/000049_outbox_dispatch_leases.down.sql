UPDATE `SRO_SHARD`.`AEGIS_OUTBOX_MESSAGE`
SET `STATUS` = 'pending', `LEASE_OWNER` = NULL, `LEASE_UNTIL` = NULL
WHERE `STATUS` = 'processing';

ALTER TABLE `SRO_SHARD`.`AEGIS_OUTBOX_MESSAGE`
    DROP CHECK `CK_AEGIS_OUTBOX_STATE`,
    DROP COLUMN `LEASE_UNTIL`,
    DROP COLUMN `LEASE_OWNER`,
    MODIFY COLUMN `STATUS` ENUM('pending', 'published', 'dead') NOT NULL DEFAULT 'pending',
    ADD CONSTRAINT `CK_AEGIS_OUTBOX_PUBLISHED` CHECK (
        (`STATUS` = 'published' AND `PUBLISHED_AT` IS NOT NULL)
        OR (`STATUS` <> 'published' AND `PUBLISHED_AT` IS NULL)
    );

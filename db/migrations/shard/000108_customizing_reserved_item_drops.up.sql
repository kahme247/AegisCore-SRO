CREATE TABLE `SRO_SHARD`.`REF_CUSTOMIZING_RESERVED_ITEM_DROP_FOR_MONSTER` (
    `SOURCE_ROW` INT UNSIGNED NOT NULL,
    `SERVICE` TINYINT UNSIGNED NOT NULL,
    `COUNTRY_MASK` TINYINT UNSIGNED NOT NULL,
    `REF_ITEM_ID` INT UNSIGNED NOT NULL,
    `PROB_RELATIVE` DOUBLE NOT NULL,
    `PROB_ABSOLUTE` DOUBLE NOT NULL,
    `ASSIGNED_GROUP` SMALLINT NOT NULL,
    `DROP_COUNT` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`SOURCE_ROW`),
    KEY `IX_REF_CUSTOM_RESERVED_DROP_LOOKUP` (`SERVICE`,`COUNTRY_MASK`,`ASSIGNED_GROUP`,`REF_ITEM_ID`),
    CONSTRAINT `CK_REF_CUSTOM_RESERVED_DROP_COUNTRY` CHECK (`COUNTRY_MASK` BETWEEN 1 AND 3),
    CONSTRAINT `CK_REF_CUSTOM_RESERVED_DROP_RELATIVE` CHECK (`PROB_RELATIVE` >= 0),
    CONSTRAINT `CK_REF_CUSTOM_RESERVED_DROP_ABSOLUTE` CHECK (`PROB_ABSOLUTE` >= 0)
) ENGINE=InnoDB;

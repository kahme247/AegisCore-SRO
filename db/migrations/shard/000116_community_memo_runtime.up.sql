CREATE TABLE `COMMUNITY_MEMO` (
  `ID` bigint unsigned NOT NULL AUTO_INCREMENT,
  `RECIPIENT_CHAR` int NOT NULL,
  `SENDER_CHAR` int DEFAULT NULL,
  `SENDER_NAME` varchar(64) NOT NULL,
  `SENDER_REF_OBJECT_ID` int unsigned NOT NULL,
  `MESSAGE` varchar(1000) NOT NULL,
  `SENT_AT` datetime(6) NOT NULL,
  `STATUS` tinyint unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`ID`),
  KEY `IX_COMMUNITY_MEMO_INBOX` (`RECIPIENT_CHAR`,`SENT_AT`,`ID`),
  CONSTRAINT `CK_COMMUNITY_MEMO_STATUS` CHECK (`STATUS` BETWEEN 0 AND 1),
  CONSTRAINT `FK_COMMUNITY_MEMO_RECIPIENT` FOREIGN KEY (`RECIPIENT_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_COMMUNITY_MEMO_SENDER` FOREIGN KEY (`SENDER_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

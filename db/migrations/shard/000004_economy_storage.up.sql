ALTER TABLE `CHAR`
    ADD COLUMN `GOLD` BIGINT UNSIGNED NOT NULL DEFAULT 1000000000 AFTER `SKILL_POINTS`;

ALTER TABLE `ITEM`
    ADD COLUMN `STACK_COUNT` SMALLINT UNSIGNED NOT NULL DEFAULT 1 AFTER `FK_REF_ITEM`,
    ADD COLUMN `OPT_LEVEL` TINYINT UNSIGNED NOT NULL DEFAULT 0 AFTER `STACK_COUNT`,
    ADD COLUMN `DATA` INT UNSIGNED NOT NULL DEFAULT 0 AFTER `OPT_LEVEL`;

CREATE TABLE `STORAGE_INFO` (
    `FK_USER` INT NOT NULL,
    `CAPACITY` TINYINT UNSIGNED NOT NULL DEFAULT 150,
    `GOLD` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (`FK_USER`),
    CONSTRAINT `FK_STORAGE_INFO_USER`
        FOREIGN KEY (`FK_USER`) REFERENCES `SRO_ACCOUNT`.`USER` (`id`)
        ON DELETE CASCADE
);

CREATE TABLE `STORAGE` (
    `FK_USER` INT NOT NULL,
    `SLOT` TINYINT UNSIGNED NOT NULL,
    `FK_ITEM` INT NOT NULL,
    PRIMARY KEY (`FK_USER`, `SLOT`),
    UNIQUE KEY `UX_STORAGE_FK_ITEM` (`FK_ITEM`),
    CONSTRAINT `FK_STORAGE_USER`
        FOREIGN KEY (`FK_USER`) REFERENCES `SRO_ACCOUNT`.`USER` (`id`)
        ON DELETE CASCADE,
    CONSTRAINT `FK_STORAGE_ITEM`
        FOREIGN KEY (`FK_ITEM`) REFERENCES `ITEM` (`id`)
);

CREATE TABLE `SHOP_GOODS` (
    `NPC_CODE_NAME` VARCHAR(128) NOT NULL,
    `TAB_INDEX` TINYINT UNSIGNED NOT NULL,
    `SLOT_INDEX` TINYINT UNSIGNED NOT NULL,
    `FK_REF_ITEM` INT NOT NULL,
    `BUY_PRICE` BIGINT UNSIGNED NOT NULL,
    `SELL_PRICE` BIGINT UNSIGNED NOT NULL,
    `OPT_LEVEL` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `VARIANCE` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `DATA` INT UNSIGNED NOT NULL DEFAULT 0,
    `MAX_STACK` INT UNSIGNED NOT NULL DEFAULT 1,
    PRIMARY KEY (`NPC_CODE_NAME`, `TAB_INDEX`, `SLOT_INDEX`),
    KEY `IX_SHOP_GOODS_REF_ITEM` (`FK_REF_ITEM`),
    CONSTRAINT `FK_SHOP_GOODS_ITEMDATA`
        FOREIGN KEY (`FK_REF_ITEM`) REFERENCES `ITEMDATA` (`ItemID`)
);

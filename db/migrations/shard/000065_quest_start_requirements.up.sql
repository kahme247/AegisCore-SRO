CREATE TABLE `SRO_SHARD`.`REF_QUEST_START_CONDITION` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `CONDITION_COUNT` SMALLINT UNSIGNED NOT NULL,
    `LEVEL_LOWER` INT UNSIGNED NOT NULL,
    `LEVEL_UPPER` INT UNSIGNED NOT NULL,
    `SYSTEM_REQUIRED` TINYINT(1) NOT NULL,
    `PARAMETERS` JSON NOT NULL,
    `RUNTIME_ENABLED` TINYINT(1) NOT NULL DEFAULT 0,
    `SCRIPT_SHA256` CHAR(64) NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`),
    CONSTRAINT `FK_REF_QUEST_START_CONDITION_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `CK_REF_QUEST_START_CONDITION_COUNT` CHECK (`CONDITION_COUNT` IN (2, 3)),
    CONSTRAINT `CK_REF_QUEST_START_LEVEL_WINDOW` CHECK (`LEVEL_LOWER` <= `LEVEL_UPPER`),
    CONSTRAINT `CK_REF_QUEST_START_CONDITION_SYSTEM` CHECK (`SYSTEM_REQUIRED` IN (0, 1)),
    CONSTRAINT `CK_REF_QUEST_START_CONDITION_PARAMETERS` CHECK (JSON_VALID(`PARAMETERS`)),
    CONSTRAINT `CK_REF_QUEST_START_CONDITION_RUNTIME` CHECK (`RUNTIME_ENABLED` IN (0, 1))
);


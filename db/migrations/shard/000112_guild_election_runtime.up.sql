CREATE TABLE `GUILD_ELECTION` (
  `ID` int unsigned NOT NULL AUTO_INCREMENT,
  `FK_GUILD` int NOT NULL,
  `PREVIOUS_MASTER` int NOT NULL,
  `WINNER_CHAR` int DEFAULT NULL,
  `STARTED_AT` datetime(6) NOT NULL,
  `ENDS_AT` datetime(6) NOT NULL,
  `ENDED_AT` datetime(6) DEFAULT NULL,
  `STATUS` enum('active','ended') NOT NULL,
  PRIMARY KEY (`ID`),
  KEY `IX_GUILD_ELECTION_ACTIVE` (`FK_GUILD`,`STATUS`,`ENDS_AT`),
  CONSTRAINT `FK_GUILD_ELECTION_GUILD` FOREIGN KEY (`FK_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE CASCADE,
  CONSTRAINT `FK_GUILD_ELECTION_PREVIOUS_MASTER` FOREIGN KEY (`PREVIOUS_MASTER`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_GUILD_ELECTION_WINNER` FOREIGN KEY (`WINNER_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `GUILD_ELECTION_CANDIDATE` (
  `FK_ELECTION` int unsigned NOT NULL,
  `FK_CHAR` int NOT NULL,
  PRIMARY KEY (`FK_ELECTION`,`FK_CHAR`),
  CONSTRAINT `FK_GUILD_ELECTION_CANDIDATE_ELECTION` FOREIGN KEY (`FK_ELECTION`) REFERENCES `GUILD_ELECTION` (`ID`) ON DELETE CASCADE,
  CONSTRAINT `FK_GUILD_ELECTION_CANDIDATE_CHAR` FOREIGN KEY (`FK_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `GUILD_ELECTION_VOTE` (
  `FK_ELECTION` int unsigned NOT NULL,
  `FK_VOTER` int NOT NULL,
  `FK_CANDIDATE` int NOT NULL,
  `VOTED_AT` datetime(6) NOT NULL,
  PRIMARY KEY (`FK_ELECTION`,`FK_VOTER`),
  KEY `IX_GUILD_ELECTION_VOTE_CANDIDATE` (`FK_ELECTION`,`FK_CANDIDATE`),
  CONSTRAINT `FK_GUILD_ELECTION_VOTE_ELECTION` FOREIGN KEY (`FK_ELECTION`) REFERENCES `GUILD_ELECTION` (`ID`) ON DELETE CASCADE,
  CONSTRAINT `FK_GUILD_ELECTION_VOTE_VOTER` FOREIGN KEY (`FK_VOTER`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_GUILD_ELECTION_VOTE_CANDIDATE` FOREIGN KEY (`FK_ELECTION`,`FK_CANDIDATE`) REFERENCES `GUILD_ELECTION_CANDIDATE` (`FK_ELECTION`,`FK_CHAR`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

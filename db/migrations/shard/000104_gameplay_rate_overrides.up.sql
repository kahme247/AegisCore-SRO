CREATE TABLE `SRO_SHARD`.`AEGIS_GAMEPLAY_RATE_OVERRIDE` (
    `EVENT_ID` VARCHAR(128) NOT NULL,
    `EXPERIENCE_RATE_PERCENT` INT UNSIGNED NOT NULL,
    `PARTY_EXPERIENCE_RATE_PERCENT` INT UNSIGNED NOT NULL,
    `SKILL_EXPERIENCE_RATE_PERCENT` INT UNSIGNED NOT NULL,
    `ACTIVATED_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`EVENT_ID`),
    KEY `idx_gameplay_rate_override_active` (`ACTIVATED_AT`, `EVENT_ID`),
    CONSTRAINT `chk_gameplay_rate_override_experience_positive` CHECK (`EXPERIENCE_RATE_PERCENT` > 0),
    CONSTRAINT `chk_gameplay_rate_override_party_positive` CHECK (`PARTY_EXPERIENCE_RATE_PERCENT` > 0),
    CONSTRAINT `chk_gameplay_rate_override_skill_positive` CHECK (`SKILL_EXPERIENCE_RATE_PERCENT` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

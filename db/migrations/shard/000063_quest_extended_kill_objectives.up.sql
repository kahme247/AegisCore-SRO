CREATE TABLE `SRO_SHARD`.`REF_QUEST_EXTENDED_KILL_OBJECTIVE` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `MISSION_INDEX` INT UNSIGNED NOT NULL,
    `DECLARATION_KIND` VARCHAR(16) NOT NULL,
    `OBJECTIVE_KEY` VARCHAR(128) NOT NULL,
    `TARGET_COUNT` SMALLINT UNSIGNED NOT NULL,
    `TARGET_CLASS` VARCHAR(128) NOT NULL,
    `PARAMETERS` JSON NOT NULL,
    `RUNTIME_ENABLED` TINYINT(1) NOT NULL DEFAULT 0,
    `SCRIPT_SHA256` CHAR(64) NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`),
    CONSTRAINT `FK_REF_QUEST_EXTENDED_KILL_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `CK_REF_QUEST_EXTENDED_KILL_KIND` CHECK (`DECLARATION_KIND` IN ('classified', 'multi_target')),
    CONSTRAINT `CK_REF_QUEST_EXTENDED_KILL_TARGET_COUNT` CHECK (`TARGET_COUNT` > 0),
    CONSTRAINT `CK_REF_QUEST_EXTENDED_KILL_PARAMETERS` CHECK (JSON_VALID(`PARAMETERS`)),
    CONSTRAINT `CK_REF_QUEST_EXTENDED_KILL_RUNTIME_ENABLED` CHECK (`RUNTIME_ENABLED` IN (0, 1))
);

CREATE TABLE `SRO_SHARD`.`REF_QUEST_EXTENDED_KILL_TARGET` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `MISSION_INDEX` INT UNSIGNED NOT NULL,
    `TARGET_INDEX` SMALLINT UNSIGNED NOT NULL,
    `TARGET_REF_OBJECT_ID` INT NOT NULL,
    `TARGET_CODE_NAME` VARCHAR(128) NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`, `TARGET_INDEX`),
    CONSTRAINT `FK_REF_QUEST_EXTENDED_KILL_TARGET_OBJECTIVE`
        FOREIGN KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`)
        REFERENCES `SRO_SHARD`.`REF_QUEST_EXTENDED_KILL_OBJECTIVE` (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`) ON DELETE CASCADE,
    CONSTRAINT `FK_REF_QUEST_EXTENDED_KILL_TARGET_OBJECT`
        FOREIGN KEY (`TARGET_REF_OBJECT_ID`) REFERENCES `SRO_SHARD`.`REF_OBJ_COMMON_VSRO` (`ID`) ON DELETE RESTRICT
);

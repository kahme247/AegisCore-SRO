CREATE TABLE `SRO_SHARD`.`REF_QUEST_SCRIPT_DECLARATION` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `CODE_NAME` VARCHAR(128) NOT NULL,
    `SOURCE_NAME` VARCHAR(255) NOT NULL,
    `SCRIPT_SHA256` CHAR(64) NOT NULL,
    `DECLARATIONS` JSON NOT NULL,
    `IMPORTED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`),
    UNIQUE KEY `UX_REF_QUEST_SCRIPT_CODE_VARIANT` (`CODE_NAME`, `VARIANT_INDEX`),
    CONSTRAINT `FK_REF_QUEST_SCRIPT_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `CK_REF_QUEST_SCRIPT_DECLARATIONS` CHECK (JSON_VALID(`DECLARATIONS`))
);

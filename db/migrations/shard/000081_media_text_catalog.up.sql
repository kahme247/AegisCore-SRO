CREATE TABLE `SRO_SHARD`.`REF_MEDIA_TEXT_CATALOG` (
    `FILE_NAME` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PRIMARY KEY (`FILE_NAME`),
    CONSTRAINT `CK_REF_MEDIA_TEXT_CATALOG_FILE` CHECK (`FILE_NAME` REGEXP '^[A-Za-z0-9_.-]+[.]txt$')
) ENGINE=InnoDB;

CREATE TABLE `SRO_SHARD`.`REF_MEDIA_TEXT_CATALOG_ROW` (
    `FILE_NAME` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `ROW_ORDINAL` INT UNSIGNED NOT NULL,
    `RAW_FIELDS` JSON NOT NULL,
    PRIMARY KEY (`FILE_NAME`, `ROW_ORDINAL`),
    CONSTRAINT `FK_REF_MEDIA_TEXT_CATALOG_ROW_FILE`
        FOREIGN KEY (`FILE_NAME`) REFERENCES `SRO_SHARD`.`REF_MEDIA_TEXT_CATALOG` (`FILE_NAME`) ON DELETE CASCADE
) ENGINE=InnoDB;

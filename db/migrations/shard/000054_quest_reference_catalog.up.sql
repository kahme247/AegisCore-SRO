CREATE TABLE `SRO_SHARD`.`REF_QUEST` (
    `ID` INT NOT NULL,
    `SERVICE` TINYINT UNSIGNED NOT NULL,
    `CODE_NAME` VARCHAR(128) NOT NULL,
    `LEVEL` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `DESCRIPTION_NAME` VARCHAR(128) NOT NULL,
    `NAME_STRING` VARCHAR(128) NOT NULL,
    `PAY_STRING` VARCHAR(128) NOT NULL,
    `CONTENTS_STRING` VARCHAR(128) NOT NULL,
    `PAY_CONTENTS` VARCHAR(128) NOT NULL,
    `NOTICE_NPC` VARCHAR(128) NOT NULL DEFAULT '',
    `NOTICE_CONDITION` VARCHAR(128) NOT NULL DEFAULT '',
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_REF_QUEST_CODE_NAME` (`CODE_NAME`)
);

CREATE TABLE `SRO_SHARD`.`REF_QUEST_REWARD` (
    `QUEST_ID` INT NOT NULL,
    `SERVICE` TINYINT UNSIGNED NOT NULL,
    `QUEST_CODE_NAME` VARCHAR(128) NOT NULL,
    `IS_VIEW` TINYINT UNSIGNED NOT NULL,
    `IS_BASIC_REWARD` TINYINT UNSIGNED NOT NULL,
    `IS_ITEM_REWARD` TINYINT UNSIGNED NOT NULL,
    `IS_CHECK_CONDITION` TINYINT UNSIGNED NOT NULL,
    `IS_CHECK_COUNTRY` TINYINT UNSIGNED NOT NULL,
    `IS_CHECK_CLASS` TINYINT UNSIGNED NOT NULL,
    `IS_CHECK_GENDER` TINYINT UNSIGNED NOT NULL,
    `GOLD` BIGINT UNSIGNED NOT NULL,
    `EXPERIENCE` BIGINT UNSIGNED NOT NULL,
    `SKILL_EXPERIENCE` BIGINT UNSIGNED NOT NULL,
    `SKILL_POINTS` BIGINT UNSIGNED NOT NULL,
    `ACADEMY_POINTS` BIGINT UNSIGNED NOT NULL,
    `ACADEMY_POINT_TYPE` VARCHAR(128) NOT NULL DEFAULT 'xxx',
    `HWAN` TINYINT UNSIGNED NOT NULL,
    `INVENTORY_SLOTS` TINYINT UNSIGNED NOT NULL,
    `ITEM_REWARD_TYPE` TINYINT UNSIGNED NOT NULL,
    `SELECTION_COUNT` TINYINT UNSIGNED NOT NULL,
    `PARAM_1` BIGINT NOT NULL DEFAULT 0,
    `PARAM_1_DESCRIPTION` VARCHAR(128) NOT NULL DEFAULT 'xxx',
    `PARAM_2` INT NOT NULL DEFAULT 0,
    `PARAM_2_DESCRIPTION` VARCHAR(128) NOT NULL DEFAULT 'xxx',
    `PARAM_3` INT NOT NULL DEFAULT 0,
    `PARAM_3_DESCRIPTION` VARCHAR(128) NOT NULL DEFAULT 'xxx',
    PRIMARY KEY (`QUEST_ID`),
    CONSTRAINT `FK_REF_QUEST_REWARD_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE
);

CREATE TABLE `SRO_SHARD`.`REF_QUEST_REWARD_ITEM` (
    `ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `QUEST_ID` INT NOT NULL,
    `SERVICE` TINYINT UNSIGNED NOT NULL,
    `QUEST_CODE_NAME` VARCHAR(128) NOT NULL,
    `REWARD_TYPE` TINYINT UNSIGNED NOT NULL,
    `ITEM_CODE_NAME` VARCHAR(128) NOT NULL,
    `OPTIONAL_ITEM_CODE` VARCHAR(128) NOT NULL DEFAULT 'xxx',
    `OPTIONAL_ITEM_COUNT` INT NOT NULL DEFAULT 0,
    `ACHIEVE_QUANTITY` INT NOT NULL,
    `RENT_ITEM_CODE_NAME` VARCHAR(128) NOT NULL DEFAULT 'xxx',
    `PARAM_1` INT NOT NULL DEFAULT 0,
    `PARAM_1_DESCRIPTION` VARCHAR(128) NOT NULL DEFAULT 'xxx',
    `PARAM_2` INT NOT NULL DEFAULT 0,
    `PARAM_2_DESCRIPTION` VARCHAR(128) NOT NULL DEFAULT 'xxx',
    PRIMARY KEY (`ID`),
    KEY `IX_REF_QUEST_REWARD_ITEM_QUEST` (`QUEST_ID`),
    CONSTRAINT `FK_REF_QUEST_REWARD_ITEM_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE
);

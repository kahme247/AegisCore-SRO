CREATE TABLE `OPERATOR_PUNISHMENT_AUDIT` (
    `ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `ACTOR_CHAR` INT NOT NULL,
    `ACTOR_ACCOUNT` INT NOT NULL,
    `TARGET_CHAR` INT NOT NULL,
    `TARGET_ACCOUNT` INT NOT NULL,
    `PREVIOUS_STATUS` INT NOT NULL,
    `NEW_STATUS` INT NOT NULL,
    `CREATED_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`ID`),
    KEY `IX_OPERATOR_PUNISHMENT_TARGET` (`TARGET_ACCOUNT`,`CREATED_AT`,`ID`),
    KEY `IX_OPERATOR_PUNISHMENT_ACTOR` (`ACTOR_ACCOUNT`,`CREATED_AT`,`ID`),
    CONSTRAINT `FK_OPERATOR_PUNISHMENT_ACTOR_CHAR` FOREIGN KEY (`ACTOR_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_OPERATOR_PUNISHMENT_TARGET_CHAR` FOREIGN KEY (`TARGET_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `CK_OPERATOR_PUNISHMENT_DISTINCT` CHECK (`ACTOR_CHAR` <> `TARGET_CHAR`),
    CONSTRAINT `CK_OPERATOR_PUNISHMENT_STATUS_CHANGE` CHECK (`PREVIOUS_STATUS` <> `NEW_STATUS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

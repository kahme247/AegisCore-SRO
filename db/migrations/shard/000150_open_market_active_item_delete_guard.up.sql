CREATE TABLE `OPEN_MARKET_ACTIVE_ITEM_GUARD` (
    `LISTING_ID` BIGINT UNSIGNED NOT NULL,
    `ITEM_ID` INT NOT NULL,
    PRIMARY KEY (`LISTING_ID`),
    UNIQUE KEY `UX_OPEN_MARKET_ACTIVE_ITEM_GUARD_ITEM` (`ITEM_ID`),
    CONSTRAINT `FK_OPEN_MARKET_ACTIVE_GUARD_LISTING` FOREIGN KEY (`LISTING_ID`) REFERENCES `OPEN_MARKET_LISTING` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_OPEN_MARKET_ACTIVE_GUARD_ITEM` FOREIGN KEY (`ITEM_ID`) REFERENCES `ITEM` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB;

INSERT INTO `OPEN_MARKET_ACTIVE_ITEM_GUARD` (`LISTING_ID`,`ITEM_ID`)
SELECT `ID`,`ITEM_ID` FROM `OPEN_MARKET_LISTING` WHERE `STATUS`=1;

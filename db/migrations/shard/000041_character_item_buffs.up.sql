CREATE TABLE `CHAR_ITEM_BUFF` (
    `CHAR_ID` INT NOT NULL,
    `SKILL_ID` INT UNSIGNED NOT NULL,
    `SOURCE_REF_ITEM_ID` INT NOT NULL,
    `EXPIRES_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`CHAR_ID`, `SKILL_ID`),
    KEY `IX_CHAR_ITEM_BUFF_EXPIRY` (`EXPIRES_AT`),
    CONSTRAINT `FK_CHAR_ITEM_BUFF_CHAR`
        FOREIGN KEY (`CHAR_ID`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `FK_CHAR_ITEM_BUFF_ITEM`
        FOREIGN KEY (`SOURCE_REF_ITEM_ID`) REFERENCES `ITEMDATA` (`ItemID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

ALTER TABLE `SRO_SHARD`.`CHAR_QUEST`
    ADD COLUMN `TIMER_REMAINING` TINYINT UNSIGNED NOT NULL DEFAULT 0 AFTER `QUEST_DATA_2`;

UPDATE `SRO_SHARD`.`CHAR_QUEST` state
JOIN `SRO_SHARD`.`REF_QUEST_COMPLETION_POLICY` policy
  ON policy.`QUEST_ID`=state.`QUEST_ID` AND policy.`VARIANT_INDEX`=0 AND policy.`RUNTIME_ENABLED`=1
SET state.`TIMER_REMAINING`=policy.`LIMIT_TIME`
WHERE state.`STATUS` IN (1,7,8) AND policy.`LIMIT_TIME` BETWEEN 1 AND 255;

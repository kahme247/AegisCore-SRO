CREATE TABLE `SRO_SHARD`.`CHAR_PREMIUM_DECORATION` (
    `CHAR_ID` INT NOT NULL,
    `TOKEN` INT UNSIGNED NOT NULL,
    `REFERENCE` INT UNSIGNED NOT NULL,
    `VALUE` INT UNSIGNED NOT NULL DEFAULT 1,
    `UPDATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`CHAR_ID`),
    CONSTRAINT `FK_CHAR_PREMIUM_DECORATION_CHAR` FOREIGN KEY (`CHAR_ID`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `CK_CHAR_PREMIUM_DECORATION_TOKEN` CHECK (`TOKEN` > 0),
    CONSTRAINT `CK_CHAR_PREMIUM_DECORATION_REFERENCE` CHECK (`REFERENCE` > 0),
    CONSTRAINT `CK_CHAR_PREMIUM_DECORATION_VALUE` CHECK (`VALUE` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `SRO_SHARD`.`REF_QUEST_COLLECTION_ITEM_OBJECTIVE` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `MISSION_INDEX` INT UNSIGNED NOT NULL,
    `DECLARATION_KIND` VARCHAR(16) NOT NULL,
    `OBJECTIVE_KEY` VARCHAR(128) NOT NULL,
    `TARGET_NPC_REF_OBJECT_ID` INT NOT NULL,
    `TARGET_NPC_CODE_NAME` VARCHAR(128) NOT NULL,
    `SOURCE_COUNT` SMALLINT UNSIGNED NOT NULL,
    `PARAMETER_6` INT UNSIGNED NOT NULL,
    `REQUIRED_COUNT` INT UNSIGNED NOT NULL,
    `ITEM_REF_OBJECT_ID` INT NOT NULL,
    `ITEM_CODE_NAME` VARCHAR(128) NOT NULL,
    `PARAMETERS` JSON NOT NULL,
    `RUNTIME_ENABLED` TINYINT(1) NOT NULL DEFAULT 0,
    `SCRIPT_SHA256` CHAR(64) NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`),
    CONSTRAINT `FK_REF_QUEST_COLLECTION_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_REF_QUEST_COLLECTION_NPC`
        FOREIGN KEY (`TARGET_NPC_REF_OBJECT_ID`) REFERENCES `SRO_SHARD`.`REF_OBJ_COMMON_VSRO` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `FK_REF_QUEST_COLLECTION_ITEM`
        FOREIGN KEY (`ITEM_REF_OBJECT_ID`) REFERENCES `SRO_SHARD`.`REF_OBJ_COMMON_VSRO` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_REF_QUEST_COLLECTION_KIND` CHECK (`DECLARATION_KIND` IN ('standard', 'extended')),
    CONSTRAINT `CK_REF_QUEST_COLLECTION_SOURCE_COUNT` CHECK (`SOURCE_COUNT` > 0),
    CONSTRAINT `CK_REF_QUEST_COLLECTION_REQUIRED_COUNT` CHECK (`REQUIRED_COUNT` > 0),
    CONSTRAINT `CK_REF_QUEST_COLLECTION_PARAMETERS` CHECK (JSON_VALID(`PARAMETERS`)),
    CONSTRAINT `CK_REF_QUEST_COLLECTION_RUNTIME_ENABLED` CHECK (`RUNTIME_ENABLED` IN (0, 1))
);

CREATE TABLE `SRO_SHARD`.`REF_QUEST_COLLECTION_ITEM_SOURCE` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `MISSION_INDEX` INT UNSIGNED NOT NULL,
    `SOURCE_INDEX` SMALLINT UNSIGNED NOT NULL,
    `MONSTER_REF_OBJECT_ID` INT NOT NULL,
    `MONSTER_CODE_NAME` VARCHAR(128) NOT NULL,
    `SOURCE_PARAMETER` DOUBLE NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`, `SOURCE_INDEX`),
    CONSTRAINT `FK_REF_QUEST_COLLECTION_SOURCE_OBJECTIVE`
        FOREIGN KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`)
        REFERENCES `SRO_SHARD`.`REF_QUEST_COLLECTION_ITEM_OBJECTIVE` (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`) ON DELETE CASCADE,
    CONSTRAINT `FK_REF_QUEST_COLLECTION_SOURCE_MONSTER`
        FOREIGN KEY (`MONSTER_REF_OBJECT_ID`) REFERENCES `SRO_SHARD`.`REF_OBJ_COMMON_VSRO` (`ID`) ON DELETE RESTRICT
);

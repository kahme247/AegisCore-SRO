CREATE TABLE `GACHA_REWARD_POOL` (
  `ID` bigint unsigned NOT NULL AUTO_INCREMENT,
  `CARD_REF_ITEM_ID` int unsigned NOT NULL,
  `SELECTION` tinyint unsigned NOT NULL,
  `REWARD_REF_ITEM_ID` int unsigned NOT NULL,
  `QUANTITY` smallint unsigned NOT NULL DEFAULT 1,
  `WEIGHT` bigint unsigned NOT NULL,
  `ENABLED` tinyint(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (`ID`),
  KEY `IX_GACHA_REWARD_POOL_DRAW` (`CARD_REF_ITEM_ID`,`SELECTION`,`ENABLED`,`ID`),
  CONSTRAINT `CK_GACHA_REWARD_POOL_QUANTITY` CHECK (`QUANTITY` > 0),
  CONSTRAINT `CK_GACHA_REWARD_POOL_WEIGHT` CHECK (`WEIGHT` > 0),
  CONSTRAINT `CK_GACHA_REWARD_POOL_ENABLED` CHECK (`ENABLED` IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

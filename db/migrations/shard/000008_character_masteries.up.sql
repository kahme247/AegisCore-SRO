CREATE TABLE `CHAR_MASTERY` (
    `CHAR_ID` INT NOT NULL,
    `MASTERY_ID` INT UNSIGNED NOT NULL,
    `LEVEL` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (`CHAR_ID`, `MASTERY_ID`),
    CONSTRAINT `fk_char_mastery_character`
        FOREIGN KEY (`CHAR_ID`) REFERENCES `CHAR` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `chk_char_mastery_level`
        CHECK (`LEVEL` > 0)
) ENGINE=InnoDB;

ALTER TABLE `SRO_SHARD`.`ITEM`
    ADD COLUMN `CREATOR_NAME` VARCHAR(17) NOT NULL DEFAULT '' AFTER `DATA`;

CREATE TABLE `SRO_SHARD`.`ITEM_QUOTATION` (
    `ID` INT NOT NULL,
    `SERVICE` INT NOT NULL,
    `ASSOC_NPC` INT NOT NULL,
    `REF_ITEM_ID` INT NOT NULL,
    `BASE_QUOT` FLOAT NOT NULL,
    `QUOT_LB` FLOAT NOT NULL,
    `QUOT_UB` FLOAT NOT NULL,
    `BASE_STOCK_AMOUNT` INT NOT NULL,
    `FLUCTUATE_AMOUNT` INT NOT NULL,
    `CUR_STOCK_AMOUNT` INT NOT NULL,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_ITEM_QUOTATION_NPC_ITEM` (`ASSOC_NPC`, `REF_ITEM_ID`),
    KEY `IX_ITEM_QUOTATION_ITEM` (`REF_ITEM_ID`),
    CONSTRAINT `FK_ITEM_QUOTATION_NPC` FOREIGN KEY (`ASSOC_NPC`) REFERENCES `CHAR_REF_DATA` (`RefObjID`),
    CONSTRAINT `FK_ITEM_QUOTATION_ITEM` FOREIGN KEY (`REF_ITEM_ID`) REFERENCES `ITEMDATA` (`ItemID`),
    CONSTRAINT `CK_ITEM_QUOTATION_SERVICE` CHECK (`SERVICE` IN (0, 1)),
    CONSTRAINT `CK_ITEM_QUOTATION_BOUNDS` CHECK (`QUOT_LB` <= `BASE_QUOT` AND `BASE_QUOT` <= `QUOT_UB`),
    CONSTRAINT `CK_ITEM_QUOTATION_STOCK` CHECK (`BASE_STOCK_AMOUNT` > 0 AND `FLUCTUATE_AMOUNT` > 0 AND `CUR_STOCK_AMOUNT` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

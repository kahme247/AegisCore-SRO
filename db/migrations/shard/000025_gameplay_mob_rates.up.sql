CREATE TABLE `GAMEPLAY_MOB_RATES` (
    `SETTING_ID` TINYINT UNSIGNED NOT NULL,
    `MOB_COUNT_RATE_PERCENT` INT UNSIGNED NOT NULL,
    `MOB_RESPAWN_RATE_PERCENT` INT UNSIGNED NOT NULL,
    `UTIME` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`SETTING_ID`),
    CONSTRAINT `chk_gameplay_mob_rates_singleton` CHECK (`SETTING_ID` = 1),
    CONSTRAINT `chk_gameplay_mob_count_rate_positive` CHECK (`MOB_COUNT_RATE_PERCENT` > 0),
    CONSTRAINT `chk_gameplay_mob_respawn_rate_positive` CHECK (`MOB_RESPAWN_RATE_PERCENT` > 0)
) ENGINE=InnoDB;


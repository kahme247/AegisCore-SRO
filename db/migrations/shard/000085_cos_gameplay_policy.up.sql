CREATE TABLE `GAMEPLAY_COS_SETTINGS` (
    `SETTING_ID` TINYINT UNSIGNED NOT NULL,
    `FOLLOW_BASE_RADIUS` FLOAT NOT NULL DEFAULT 30,
    `FOLLOW_RADIUS_STEP` FLOAT NOT NULL DEFAULT 4,
    `ORBIT_MIN_RADIUS` FLOAT NOT NULL DEFAULT 38,
    `ORBIT_RADIUS_VARIANCE` INT UNSIGNED NOT NULL DEFAULT 2001,
    `PICKUP_IDLE_MIN_RADIUS` FLOAT NOT NULL DEFAULT 30,
    `PICKUP_IDLE_VARIANCE` INT UNSIGNED NOT NULL DEFAULT 2001,
    `PICKUP_COLLECTION_RANGE` FLOAT NOT NULL DEFAULT 160,
    `COMPANION_RELOCATE_RANGE` FLOAT NOT NULL DEFAULT 80,
    `PICKUP_PET_RELOCATE_RANGE` FLOAT NOT NULL DEFAULT 190,
    `ORBIT_MIN_ANGLE_STEP` FLOAT NOT NULL DEFAULT 45,
    `ORBIT_ANGLE_STEP_RANGE` INT UNSIGNED NOT NULL DEFAULT 41,
    `ARRIVAL_RADIUS` FLOAT NOT NULL DEFAULT 3,
    `DESTINATION_MATCH_RANGE` FLOAT NOT NULL DEFAULT 2.5,
    `COMBAT_LEASH_RANGE` FLOAT NOT NULL DEFAULT 250,
    `FOLLOW_UPDATE_MS` INT UNSIGNED NOT NULL DEFAULT 500,
    `RENTAL_RETRY_MS` INT UNSIGNED NOT NULL DEFAULT 5000,
    `DEFAULT_ATTACK_COOLDOWN_MS` INT UNSIGNED NOT NULL DEFAULT 1500,
    `IDLE_WAYPOINT_MIN_MS` INT UNSIGNED NOT NULL DEFAULT 2000,
    `IDLE_WAYPOINT_VARIANCE_MS` INT UNSIGNED NOT NULL DEFAULT 3000,
    `UPDATED_AT` TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`SETTING_ID`),
    CONSTRAINT `CK_GAMEPLAY_COS_SETTINGS_SINGLETON` CHECK (`SETTING_ID` = 1),
    CONSTRAINT `CK_GAMEPLAY_COS_SETTINGS_POSITIVE` CHECK (
        `FOLLOW_BASE_RADIUS` > 0 AND `FOLLOW_RADIUS_STEP` > 0 AND `ORBIT_MIN_RADIUS` > 0
        AND `ORBIT_RADIUS_VARIANCE` > 0 AND `PICKUP_IDLE_MIN_RADIUS` > 0 AND `PICKUP_IDLE_VARIANCE` > 0
        AND `PICKUP_COLLECTION_RANGE` > 0 AND `COMPANION_RELOCATE_RANGE` > 0 AND `PICKUP_PET_RELOCATE_RANGE` > 0
        AND `ORBIT_MIN_ANGLE_STEP` > 0 AND `ORBIT_ANGLE_STEP_RANGE` > 0 AND `ARRIVAL_RADIUS` > 0
        AND `DESTINATION_MATCH_RANGE` > 0 AND `COMBAT_LEASH_RANGE` > 0 AND `FOLLOW_UPDATE_MS` > 0
        AND `RENTAL_RETRY_MS` > 0 AND `DEFAULT_ATTACK_COOLDOWN_MS` > 0 AND `IDLE_WAYPOINT_MIN_MS` > 0
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;


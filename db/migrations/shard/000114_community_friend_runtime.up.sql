CREATE TABLE `COMMUNITY_FRIEND_REQUEST` (
  `CHAR_LOW` int NOT NULL,
  `CHAR_HIGH` int NOT NULL,
  `REQUESTER_CHAR` int NOT NULL,
  `TARGET_CHAR` int NOT NULL,
  `REQUESTED_AT` datetime(6) NOT NULL,
  PRIMARY KEY (`CHAR_LOW`,`CHAR_HIGH`),
  KEY `IX_COMMUNITY_FRIEND_REQUEST_TARGET` (`TARGET_CHAR`,`REQUESTED_AT`),
  CONSTRAINT `CK_COMMUNITY_FRIEND_REQUEST_ORDER` CHECK (`CHAR_LOW` < `CHAR_HIGH`),
  CONSTRAINT `CK_COMMUNITY_FRIEND_REQUEST_DIRECTION` CHECK ((`REQUESTER_CHAR`=`CHAR_LOW` AND `TARGET_CHAR`=`CHAR_HIGH`) OR (`REQUESTER_CHAR`=`CHAR_HIGH` AND `TARGET_CHAR`=`CHAR_LOW`)),
  CONSTRAINT `FK_COMMUNITY_FRIEND_REQUEST_LOW` FOREIGN KEY (`CHAR_LOW`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_COMMUNITY_FRIEND_REQUEST_HIGH` FOREIGN KEY (`CHAR_HIGH`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_COMMUNITY_FRIEND_REQUEST_REQUESTER` FOREIGN KEY (`REQUESTER_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_COMMUNITY_FRIEND_REQUEST_TARGET` FOREIGN KEY (`TARGET_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `COMMUNITY_FRIEND` (
  `CHAR_LOW` int NOT NULL,
  `CHAR_HIGH` int NOT NULL,
  `ACCEPTED_AT` datetime(6) NOT NULL,
  PRIMARY KEY (`CHAR_LOW`,`CHAR_HIGH`),
  KEY `IX_COMMUNITY_FRIEND_HIGH` (`CHAR_HIGH`,`CHAR_LOW`),
  CONSTRAINT `CK_COMMUNITY_FRIEND_ORDER` CHECK (`CHAR_LOW` < `CHAR_HIGH`),
  CONSTRAINT `FK_COMMUNITY_FRIEND_LOW` FOREIGN KEY (`CHAR_LOW`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_COMMUNITY_FRIEND_HIGH` FOREIGN KEY (`CHAR_HIGH`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

    CONSTRAINT `CK_SERVER_EVENT_INSTANCE_TARGET` CHECK (`TARGET_PROGRESS` > 0),
    CONSTRAINT `CK_SERVER_EVENT_INSTANCE_STATE` CHECK (`STATE` BETWEEN 1 AND 3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;


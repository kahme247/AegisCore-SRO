CREATE TABLE `CHAR_ITEM_SERVICE` (
    `CHAR_ID` INT NOT NULL,
    `SERVICE_KIND` TINYINT UNSIGNED NOT NULL COMMENT '1=Gold/Premium, 2=Skill Gold',
    `SOURCE_REF_ITEM_ID` INT NOT NULL,
    `EXPERIENCE_BONUS_PERCENT` INT UNSIGNED NOT NULL DEFAULT 0,
    `SKILL_EXPERIENCE_BONUS_PERCENT` INT UNSIGNED NOT NULL DEFAULT 0,
    `DAILY_BUDGET_MS` INT UNSIGNED NOT NULL DEFAULT 10800000,
    `ACTIVATED_AT` DATETIME(6) NOT NULL,
    `EXPIRES_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`CHAR_ID`, `SERVICE_KIND`),
    CONSTRAINT `FK_CHAR_ITEM_SERVICE_CHAR` FOREIGN KEY (`CHAR_ID`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `FK_CHAR_ITEM_SERVICE_ITEM` FOREIGN KEY (`SOURCE_REF_ITEM_ID`) REFERENCES `ITEMDATA` (`ItemID`),
    CONSTRAINT `CK_CHAR_ITEM_SERVICE_KIND` CHECK (`SERVICE_KIND` IN (1, 2)),
    CONSTRAINT `CK_CHAR_ITEM_SERVICE_EXPIRY` CHECK (`EXPIRES_AT` > `ACTIVATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

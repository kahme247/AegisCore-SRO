ALTER TABLE `SRO_SHARD`.`AEGIS_OUTBOX_MESSAGE`
    DROP CHECK `CK_AEGIS_OUTBOX_PUBLISHED`,
    MODIFY COLUMN `STATUS` ENUM('pending', 'processing', 'published', 'dead') NOT NULL DEFAULT 'pending',
    ADD COLUMN `LEASE_OWNER` VARCHAR(128) NULL AFTER `ATTEMPT_COUNT`,
    ADD COLUMN `LEASE_UNTIL` DATETIME(6) NULL AFTER `LEASE_OWNER`,
    ADD CONSTRAINT `CK_AEGIS_OUTBOX_STATE` CHECK (
        (`STATUS` = 'pending' AND `PUBLISHED_AT` IS NULL AND `LEASE_OWNER` IS NULL AND `LEASE_UNTIL` IS NULL)
        OR (`STATUS` = 'processing' AND `PUBLISHED_AT` IS NULL AND `LEASE_OWNER` IS NOT NULL AND `LEASE_UNTIL` IS NOT NULL)
        OR (`STATUS` = 'published' AND `PUBLISHED_AT` IS NOT NULL AND `LEASE_OWNER` IS NULL AND `LEASE_UNTIL` IS NULL)
        OR (`STATUS` = 'dead' AND `PUBLISHED_AT` IS NULL AND `LEASE_OWNER` IS NULL AND `LEASE_UNTIL` IS NULL)
    );

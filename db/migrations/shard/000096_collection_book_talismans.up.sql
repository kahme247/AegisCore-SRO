CREATE TABLE `SRO_SHARD`.`REF_COLLECTION_BOOK_THEME` (
    `THEME_ID` INT UNSIGNED NOT NULL,
    `CODE_NAME` VARCHAR(128) NOT NULL,
    `COMPLETE_COUNT` SMALLINT UNSIGNED NOT NULL,
    PRIMARY KEY (`THEME_ID`), UNIQUE KEY `UQ_REF_COLLECTION_BOOK_THEME_CODE` (`CODE_NAME`),
    CONSTRAINT `CK_REF_COLLECTION_BOOK_THEME_COMPLETE` CHECK (`COMPLETE_COUNT` > 0)
);

CREATE TABLE `SRO_SHARD`.`REF_COLLECTION_BOOK_ITEM` (
    `ITEM_REF_OBJECT_ID` INT UNSIGNED NOT NULL,
    `ITEM_CODE_NAME` VARCHAR(128) NOT NULL,
    `THEME_ID` INT UNSIGNED NOT NULL,
    `SLOT_INDEX` SMALLINT UNSIGNED NOT NULL,
    PRIMARY KEY (`ITEM_REF_OBJECT_ID`), UNIQUE KEY `UQ_REF_COLLECTION_BOOK_ITEM_CODE` (`ITEM_CODE_NAME`),
    UNIQUE KEY `UQ_REF_COLLECTION_BOOK_ITEM_SLOT` (`THEME_ID`,`SLOT_INDEX`),
    CONSTRAINT `FK_REF_COLLECTION_BOOK_ITEM_THEME` FOREIGN KEY (`THEME_ID`) REFERENCES `SRO_SHARD`.`REF_COLLECTION_BOOK_THEME` (`THEME_ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_REF_COLLECTION_BOOK_ITEM_SLOT` CHECK (`SLOT_INDEX` > 0)
);

CREATE TABLE `SRO_SHARD`.`CHAR_COLLECTION_BOOK` (
    `CHAR_ID` INT NOT NULL,
    `THEME_ID` INT UNSIGNED NOT NULL,
    `SLOT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `ITEM_REF_OBJECT_ID` INT UNSIGNED NOT NULL,
    `REGISTERED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`CHAR_ID`,`THEME_ID`,`SLOT_INDEX`),
    UNIQUE KEY `UQ_CHAR_COLLECTION_BOOK_ITEM` (`CHAR_ID`,`ITEM_REF_OBJECT_ID`),
    CONSTRAINT `FK_CHAR_COLLECTION_BOOK_CHAR` FOREIGN KEY (`CHAR_ID`) REFERENCES `SRO_SHARD`.`CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `FK_CHAR_COLLECTION_BOOK_ITEM` FOREIGN KEY (`ITEM_REF_OBJECT_ID`) REFERENCES `SRO_SHARD`.`REF_COLLECTION_BOOK_ITEM` (`ITEM_REF_OBJECT_ID`) ON DELETE RESTRICT,
    CONSTRAINT `FK_CHAR_COLLECTION_BOOK_THEME` FOREIGN KEY (`THEME_ID`) REFERENCES `SRO_SHARD`.`REF_COLLECTION_BOOK_THEME` (`THEME_ID`) ON DELETE RESTRICT
);


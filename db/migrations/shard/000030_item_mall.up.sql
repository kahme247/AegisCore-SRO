CREATE TABLE `ITEM_MALL_GOODS` (
    `REF_SHOP_GROUP_ID` SMALLINT UNSIGNED NOT NULL,
    `GROUP_INDEX` TINYINT UNSIGNED NOT NULL,
    `TAB_INDEX` TINYINT UNSIGNED NOT NULL,
    `SLOT_INDEX` TINYINT UNSIGNED NOT NULL,
    `PACKAGE_ID` INT UNSIGNED NOT NULL,
    `PACKAGE_CODE_NAME` VARCHAR(128) NOT NULL,
    `FK_REF_ITEM` INT NOT NULL,
    `CURRENCY` TINYINT UNSIGNED NOT NULL COMMENT '0=Silk, 1=Gift Silk, 2=Silk Point',
    `PRICE` INT UNSIGNED NOT NULL,
    `QUANTITY` SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    `OPT_LEVEL` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `VARIANCE` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `DATA` INT UNSIGNED NOT NULL DEFAULT 0,
    `RENT_TYPE` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `RENT_CAN_DELETE` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `RENT_CAN_RECHARGE` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `RENT_PERIOD_BEGIN_TIME` INT UNSIGNED NOT NULL DEFAULT 0,
    `RENT_PERIOD_END_TIME` INT UNSIGNED NOT NULL DEFAULT 0,
    `RENT_METER_RATE_TIME` INT UNSIGNED NOT NULL DEFAULT 0,
    `RENT_PACKING_TIME` INT UNSIGNED NOT NULL DEFAULT 0,
    `ENABLED` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    PRIMARY KEY (`REF_SHOP_GROUP_ID`, `GROUP_INDEX`, `TAB_INDEX`, `SLOT_INDEX`),
    KEY `IX_ITEM_MALL_GOODS_PACKAGE_ID` (`PACKAGE_ID`),
    CONSTRAINT `CK_ITEM_MALL_GOODS_CURRENCY` CHECK (`CURRENCY` <= 2),
    CONSTRAINT `CK_ITEM_MALL_GOODS_QUANTITY` CHECK (`QUANTITY` > 0),
    CONSTRAINT `FK_ITEM_MALL_GOODS_ITEMDATA` FOREIGN KEY (`FK_REF_ITEM`) REFERENCES `ITEMDATA` (`ItemID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `ITEM_MALL_PURCHASE` (
    `ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `FK_USER` INT NOT NULL,
    `FK_CHAR` INT NOT NULL,
    `PACKAGE_ID` INT UNSIGNED NOT NULL,
    `PACKAGE_CODE_NAME` VARCHAR(128) NOT NULL,
    `FK_REF_ITEM` INT NOT NULL,
    `CURRENCY` TINYINT UNSIGNED NOT NULL,
    `PRICE` INT UNSIGNED NOT NULL,
    `QUANTITY` SMALLINT UNSIGNED NOT NULL,
    `CTIME` TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`ID`),
    KEY `IX_ITEM_MALL_PURCHASE_USER_TIME` (`FK_USER`, `CTIME`),
    KEY `IX_ITEM_MALL_PURCHASE_CHAR_TIME` (`FK_CHAR`, `CTIME`),
    CONSTRAINT `FK_ITEM_MALL_PURCHASE_USER` FOREIGN KEY (`FK_USER`) REFERENCES `SRO_ACCOUNT`.`USER` (`id`),
    CONSTRAINT `FK_ITEM_MALL_PURCHASE_CHAR` FOREIGN KEY (`FK_CHAR`) REFERENCES `CHAR` (`id`),
    CONSTRAINT `FK_ITEM_MALL_PURCHASE_ITEMDATA` FOREIGN KEY (`FK_REF_ITEM`) REFERENCES `ITEMDATA` (`ItemID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

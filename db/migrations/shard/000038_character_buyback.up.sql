CREATE TABLE `CHAR_BUYBACK` (
    `FK_CHAR` INT NOT NULL,
    `SLOT` TINYINT UNSIGNED NOT NULL,
    `FK_ITEM` INT NOT NULL,
    `PRICE` BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (`FK_CHAR`, `SLOT`),
    UNIQUE KEY `UX_CHAR_BUYBACK_ITEM` (`FK_ITEM`),
    CONSTRAINT `CK_CHAR_BUYBACK_SLOT` CHECK (`SLOT` < 5),
    CONSTRAINT `FK_CHAR_BUYBACK_CHAR` FOREIGN KEY (`FK_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `FK_CHAR_BUYBACK_ITEM` FOREIGN KEY (`FK_ITEM`) REFERENCES `ITEM` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

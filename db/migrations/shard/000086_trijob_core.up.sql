CREATE TABLE `SRO_SHARD`.`REF_JOB_LEVEL_EXPERIENCE` (
    `JOB_LEVEL` TINYINT UNSIGNED NOT NULL,
    `REQUIRED_EXPERIENCE` BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (`JOB_LEVEL`),
    CONSTRAINT `CK_REF_JOB_LEVEL_EXPERIENCE_LEVEL` CHECK (`JOB_LEVEL` BETWEEN 1 AND 10),
    CONSTRAINT `CK_REF_JOB_LEVEL_EXPERIENCE_REQUIRED` CHECK (`REQUIRED_EXPERIENCE` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

INSERT INTO `SRO_SHARD`.`REF_JOB_LEVEL_EXPERIENCE` (`JOB_LEVEL`, `REQUIRED_EXPERIENCE`)
SELECT `LEVEL`, `REQUIRED_JOB_EXPERIENCE`
FROM `SRO_SHARD`.`REF_LEVEL_DATA`
WHERE `LEVEL` BETWEEN 1 AND 10 AND `REQUIRED_JOB_EXPERIENCE` > 0;

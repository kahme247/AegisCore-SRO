    ADD COLUMN `ENROLLMENT_FEE` INT UNSIGNED NOT NULL DEFAULT 0 AFTER `PENDING_REWARD_GOLD`,
    ADD COLUMN `PREVIOUS_JOB_TYPE` TINYINT UNSIGNED NOT NULL DEFAULT 0 AFTER `LEAVE_AVAILABLE_AT`,
    ADD COLUMN `PREVIOUS_JOB_EXP` BIGINT UNSIGNED NOT NULL DEFAULT 0 AFTER `PREVIOUS_JOB_TYPE`,

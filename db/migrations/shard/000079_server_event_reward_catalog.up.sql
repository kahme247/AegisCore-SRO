CREATE TABLE `SRO_SHARD`.`REF_SERVER_EVENT_REWARD` (
    `REWARD_ID` INT NOT NULL,
    `REF_SKILL_ID` INT NOT NULL DEFAULT 0,
    `REWARD_CLASS` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `FLAGS` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `APPLY_TIME` INT NOT NULL DEFAULT 0,
    `REF_VALUE_1` BIGINT NOT NULL DEFAULT 0,
    `REF_VALUE_2` BIGINT NOT NULL DEFAULT 0,
    `REF_VALUE_3` BIGINT NOT NULL DEFAULT 0,
    `EXP_RATIO` REAL NOT NULL DEFAULT 0,
    `SKILL_EXP_RATIO` REAL NOT NULL DEFAULT 0,
    `RAW_FIELDS` TEXT NULL,
    PRIMARY KEY (`REWARD_ID`)
);

CREATE TABLE `SRO_SHARD`.`REF_SERVER_EVENT_REWARD_EXP_UP_FOR_PLAYERS` (
    `REWARD_ID` INT NOT NULL,
    `EXP_RATIO` REAL NOT NULL DEFAULT 0,
    `SKILL_EXP_RATIO` REAL NOT NULL DEFAULT 0,
    PRIMARY KEY (`REWARD_ID`),
    CONSTRAINT `FK_REF_SERVER_EVENT_REWARD_EXP`
        FOREIGN KEY (`REWARD_ID`) REFERENCES `SRO_SHARD`.`REF_SERVER_EVENT_REWARD` (`REWARD_ID`) ON DELETE CASCADE
);

CREATE TABLE `SRO_SHARD`.`REF_SERVER_EVENT_REWARD_SPAWN_MONSTER` (
    `REWARD_ID` INT NOT NULL,
    `REF_OBJ_ID` INT NOT NULL DEFAULT 0,
    `MONSTER_COUNT` INT NOT NULL DEFAULT 0,
    `LEVEL` INT NOT NULL DEFAULT 0,
    `PARAM_1` BIGINT NOT NULL DEFAULT 0,
    `PARAM_2` BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (`REWARD_ID`),
    CONSTRAINT `FK_REF_SERVER_EVENT_REWARD_SPAWN`
        FOREIGN KEY (`REWARD_ID`) REFERENCES `SRO_SHARD`.`REF_SERVER_EVENT_REWARD` (`REWARD_ID`) ON DELETE CASCADE
);

CREATE TABLE `SRO_SHARD`.`REF_SERVER_EVENT_REWARD_EVENT` (
    `SERVER_EVENT_ID` INT NOT NULL,
    `REWARD_ID` INT NOT NULL,
    `AQ_TYPE` INT NOT NULL DEFAULT 0,
    PRIMARY KEY (`SERVER_EVENT_ID`, `REWARD_ID`),
    KEY `IX_REF_SERVER_EVENT_REWARD_EVENT_REWARD` (`REWARD_ID`),
    CONSTRAINT `FK_REF_SERVER_EVENT_REWARD_EVENT_REWARD`
        FOREIGN KEY (`REWARD_ID`) REFERENCES `SRO_SHARD`.`REF_SERVER_EVENT_REWARD` (`REWARD_ID`) ON DELETE CASCADE
);

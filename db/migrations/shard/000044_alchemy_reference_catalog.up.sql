CREATE TABLE `REF_MAGIC_OPTION` (
    `ID` INT UNSIGNED NOT NULL,
    `CODE_NAME` VARCHAR(64) NOT NULL,
    `OPTION_LEVEL` TINYINT UNSIGNED NOT NULL,
    `PARAM_TYPE` INT UNSIGNED NOT NULL,
    `PARAM_VALUE` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_REF_MAGIC_OPTION_CODE_LEVEL` (`CODE_NAME`, `OPTION_LEVEL`),
    KEY `IX_REF_MAGIC_OPTION_CODE` (`CODE_NAME`),
    CONSTRAINT `CK_REF_MAGIC_OPTION_LEVEL` CHECK (`OPTION_LEVEL` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

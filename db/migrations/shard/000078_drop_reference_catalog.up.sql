-- Normalized runtime projections of the vSRO drop-reference families.
-- The importer preserves the original CSV/textdata rows while these typed
-- columns provide the selectors with stable, indexed joins.
CREATE TABLE `SRO_SHARD`.`REF_DROP_GOLD` (
    `MON_LEVEL` INT UNSIGNED NOT NULL,
    `SERVICE` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    `DROP_PROB` DOUBLE NOT NULL,
    `GOLD_MIN` BIGINT UNSIGNED NOT NULL,
    `GOLD_MAX` BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (`MON_LEVEL`),
    CONSTRAINT `CK_REF_DROP_GOLD_RANGE` CHECK (`GOLD_MAX` >= `GOLD_MIN`),
    KEY `IX_REF_DROP_GOLD_SERVICE` (`SERVICE`)
) ENGINE=InnoDB;

CREATE TABLE `SRO_SHARD`.`REF_DROP_ITEM_GROUP` (
    `SERVICE` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    `REF_ITEM_GROUP_ID` INT UNSIGNED NOT NULL,
    `REF_ITEM_ID` INT UNSIGNED NOT NULL,
    `SELECT_RATIO` DOUBLE NOT NULL,
    PRIMARY KEY (`REF_ITEM_GROUP_ID`,`REF_ITEM_ID`),
    KEY `IX_REF_DROP_ITEM_GROUP_SERVICE` (`SERVICE`),
    CONSTRAINT `CK_REF_DROP_ITEM_GROUP_RATIO` CHECK (`SELECT_RATIO` >= 0)
) ENGINE=InnoDB;

CREATE TABLE `SRO_SHARD`.`REF_MONSTER_ASSIGNED_ITEM_RND_DROP` (
    `SERVICE` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    `REF_MONSTER_ID` INT UNSIGNED NOT NULL,
    `REF_ITEM_GROUP_ID` INT UNSIGNED NOT NULL,
    `OVERLAP` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `DROP_AMOUNT_MIN` TINYINT UNSIGNED NOT NULL,
    `DROP_AMOUNT_MAX` TINYINT UNSIGNED NOT NULL,
    `DROP_RATIO` DOUBLE NOT NULL,
    PRIMARY KEY (`REF_MONSTER_ID`,`REF_ITEM_GROUP_ID`),
    KEY `IX_REF_MONSTER_RND_DROP_SERVICE` (`SERVICE`),
    CONSTRAINT `CK_REF_MONSTER_RND_DROP_AMOUNT` CHECK (`DROP_AMOUNT_MAX` >= `DROP_AMOUNT_MIN`),
    CONSTRAINT `CK_REF_MONSTER_RND_DROP_RATIO` CHECK (`DROP_RATIO` >= 0)
) ENGINE=InnoDB;

CREATE TABLE `SRO_SHARD`.`REF_MONSTER_ASSIGNED_ITEM_DROP` (

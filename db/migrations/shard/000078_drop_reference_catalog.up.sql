    `DROP_AMOUNT_MIN` TINYINT UNSIGNED NOT NULL,
    `DROP_AMOUNT_MAX` TINYINT UNSIGNED NOT NULL,
    `DROP_RATIO` DOUBLE NOT NULL,
    `REF_MAGIC_OPTION_ID1` INT UNSIGNED NULL,
    `CUSTOM_VALUE1` INT UNSIGNED NOT NULL DEFAULT 0,
    `REF_MAGIC_OPTION_ID2` INT UNSIGNED NULL,
    `CUSTOM_VALUE2` INT UNSIGNED NOT NULL DEFAULT 0,
    `REF_MAGIC_OPTION_ID3` INT UNSIGNED NULL,
    `CUSTOM_VALUE3` INT UNSIGNED NOT NULL DEFAULT 0,
    `REF_MAGIC_OPTION_ID4` INT UNSIGNED NULL,
    `CUSTOM_VALUE4` INT UNSIGNED NOT NULL DEFAULT 0,
    `REF_MAGIC_OPTION_ID5` INT UNSIGNED NULL,
    `CUSTOM_VALUE5` INT UNSIGNED NOT NULL DEFAULT 0,
    `REF_MAGIC_OPTION_ID6` INT UNSIGNED NULL,
    `CUSTOM_VALUE6` INT UNSIGNED NOT NULL DEFAULT 0,
    `REF_MAGIC_OPTION_ID7` INT UNSIGNED NULL,
    `CUSTOM_VALUE7` INT UNSIGNED NOT NULL DEFAULT 0,

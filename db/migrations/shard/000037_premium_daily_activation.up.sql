CREATE TABLE `CHAR_ITEM_SERVICE_DAILY` (
    `CHAR_ID` INT NOT NULL,
    `SERVICE_KIND` TINYINT UNSIGNED NOT NULL,
    `USED_ON` DATE NOT NULL,
    `ACTIVE_UNTIL` DATETIME(6) NOT NULL,
    PRIMARY KEY (`CHAR_ID`, `SERVICE_KIND`),
    CONSTRAINT `FK_CHAR_ITEM_SERVICE_DAILY_SERVICE`
        FOREIGN KEY (`CHAR_ID`, `SERVICE_KIND`)
        REFERENCES `CHAR_ITEM_SERVICE` (`CHAR_ID`, `SERVICE_KIND`)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

ALTER TABLE `SRO_SHARD`.`REF_JOB_LEVEL_EXPERIENCE`
    DROP CHECK `CK_REF_JOB_LEVEL_EXPERIENCE_LEVEL`,
    ADD CONSTRAINT `CK_REF_JOB_LEVEL_EXPERIENCE_LEVEL` CHECK (`JOB_LEVEL` BETWEEN 1 AND 10);

INSERT INTO `SRO_SHARD`.`REF_JOB_LEVEL_EXPERIENCE` (`JOB_LEVEL`, `REQUIRED_EXPERIENCE`)
SELECT `LEVEL`, `REQUIRED_JOB_EXPERIENCE`
FROM `SRO_SHARD`.`REF_LEVEL_DATA`
WHERE `LEVEL` BETWEEN 8 AND 10 AND `REQUIRED_JOB_EXPERIENCE` > 0
ON DUPLICATE KEY UPDATE `REQUIRED_EXPERIENCE`=VALUES(`REQUIRED_EXPERIENCE`);

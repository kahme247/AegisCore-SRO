CREATE TABLE `SRO_SHARD`.`REF_QUEST_DELIVER_ITEM` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `MISSION_INDEX` INT UNSIGNED NOT NULL,
    `OBJECTIVE_KEY` VARCHAR(128) NOT NULL,
    `TARGET_NPC_REF_OBJECT_ID` INT NOT NULL,
    `TARGET_NPC_CODE_NAME` VARCHAR(128) NOT NULL,
    `ITEM_COUNT` SMALLINT UNSIGNED NOT NULL,
    `TRAILING_PARAMETER` INT UNSIGNED NOT NULL,
    `DIALOGUE_KEY` VARCHAR(128) NOT NULL,
    `PARAMETERS` JSON NOT NULL,
    `RUNTIME_ENABLED` TINYINT(1) NOT NULL DEFAULT 0,
    `SCRIPT_SHA256` CHAR(64) NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`),
    CONSTRAINT `FK_REF_QUEST_DELIVER_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_REF_QUEST_DELIVER_NPC`
        FOREIGN KEY (`TARGET_NPC_REF_OBJECT_ID`) REFERENCES `SRO_SHARD`.`REF_OBJ_COMMON_VSRO` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_REF_QUEST_DELIVER_ITEM_COUNT` CHECK (`ITEM_COUNT` > 0),
    CONSTRAINT `CK_REF_QUEST_DELIVER_PARAMETERS` CHECK (JSON_VALID(`PARAMETERS`)),
    CONSTRAINT `CK_REF_QUEST_DELIVER_RUNTIME_ENABLED` CHECK (`RUNTIME_ENABLED` IN (0, 1))
);

CREATE TABLE `SRO_SHARD`.`REF_QUEST_DELIVER_ITEM_ENTRY` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `MISSION_INDEX` INT UNSIGNED NOT NULL,
    `ITEM_INDEX` SMALLINT UNSIGNED NOT NULL,
    `ITEM_REF_OBJECT_ID` INT NOT NULL,
    `ITEM_CODE_NAME` VARCHAR(128) NOT NULL,
    `QUANTITY` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`, `ITEM_INDEX`),
    CONSTRAINT `FK_REF_QUEST_DELIVER_ENTRY_OBJECTIVE`
        FOREIGN KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`)
        REFERENCES `SRO_SHARD`.`REF_QUEST_DELIVER_ITEM` (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`) ON DELETE CASCADE,
    CONSTRAINT `FK_REF_QUEST_DELIVER_ENTRY_ITEM`
        FOREIGN KEY (`ITEM_REF_OBJECT_ID`) REFERENCES `SRO_SHARD`.`REF_OBJ_COMMON_VSRO` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_REF_QUEST_DELIVER_ENTRY_QUANTITY` CHECK (`QUANTITY` > 0)
);

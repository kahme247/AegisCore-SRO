CREATE TABLE `SRO_SHARD`.`AEGIS_GAMEPLAY_MOB_RATE_OVERRIDE` (
    `EVENT_ID` VARCHAR(128) NOT NULL,
    `MOB_COUNT_RATE_PERCENT` INT UNSIGNED NOT NULL,
    `MOB_RESPAWN_RATE_PERCENT` INT UNSIGNED NOT NULL,
    `LOOT_DROP_RATE_PERCENT` INT UNSIGNED NOT NULL,
    `ACTIVATED_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`EVENT_ID`),
    KEY `idx_gameplay_mob_rate_override_active` (`ACTIVATED_AT`, `EVENT_ID`),
    CONSTRAINT `chk_gameplay_mob_override_count_positive` CHECK (`MOB_COUNT_RATE_PERCENT` > 0),
    CONSTRAINT `chk_gameplay_mob_override_respawn_positive` CHECK (`MOB_RESPAWN_RATE_PERCENT` > 0),
    CONSTRAINT `chk_gameplay_mob_override_drop_positive` CHECK (`LOOT_DROP_RATE_PERCENT` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

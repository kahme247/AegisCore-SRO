CREATE TABLE `ITEM_MAGIC_OPTION` (
    `FK_ITEM` INT NOT NULL,
    `SLOT` TINYINT UNSIGNED NOT NULL,
    `TYPE` INT UNSIGNED NOT NULL,
    `VALUE` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`FK_ITEM`, `SLOT`),
    CONSTRAINT `CK_ITEM_MAGIC_OPTION_SLOT` CHECK (`SLOT` < 12),
    CONSTRAINT `FK_ITEM_MAGIC_OPTION_ITEM` FOREIGN KEY (`FK_ITEM`) REFERENCES `ITEM` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `ITEM_BINDING_OPTION` (
    `FK_ITEM` INT NOT NULL,
    `OPTION_TYPE` TINYINT UNSIGNED NOT NULL,
    `SLOT` TINYINT UNSIGNED NOT NULL,
    `OPTION_ID` INT UNSIGNED NOT NULL,
    `OPTION_VALUE` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`FK_ITEM`, `OPTION_TYPE`, `SLOT`),
    CONSTRAINT `CK_ITEM_BINDING_OPTION_TYPE` CHECK (`OPTION_TYPE` IN (1, 2)),
    CONSTRAINT `CK_ITEM_BINDING_OPTION_SLOT` CHECK (`SLOT` < 12),
    CONSTRAINT `FK_ITEM_BINDING_OPTION_ITEM` FOREIGN KEY (`FK_ITEM`) REFERENCES `ITEM` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `ITEM_ALCHEMY_PROTECTION` (
    `FK_ITEM` INT NOT NULL,
    `ASTRAL` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `IMMORTAL` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `STEADY` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (`FK_ITEM`),
    CONSTRAINT `CK_ITEM_ALCHEMY_ASTRAL` CHECK (`ASTRAL` <= 6),
    CONSTRAINT `CK_ITEM_ALCHEMY_IMMORTAL` CHECK (`IMMORTAL` <= 6),
    CONSTRAINT `CK_ITEM_ALCHEMY_STEADY` CHECK (`STEADY` <= 6),
    CONSTRAINT `CK_ITEM_ALCHEMY_ASTRAL_IMMORTAL` CHECK (`ASTRAL` <= `IMMORTAL`),
    CONSTRAINT `FK_ITEM_ALCHEMY_PROTECTION_ITEM` FOREIGN KEY (`FK_ITEM`) REFERENCES `ITEM` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `AVATAR_INVENTORY` (
    `FK_CHAR` INT NOT NULL,
    `SLOT` TINYINT UNSIGNED NOT NULL,
    `FK_ITEM` INT NOT NULL,
    PRIMARY KEY (`FK_CHAR`, `SLOT`),
    UNIQUE KEY `UX_AVATAR_INVENTORY_ITEM` (`FK_ITEM`),
    CONSTRAINT `CK_AVATAR_INVENTORY_SLOT` CHECK (`SLOT` < 5),
    CONSTRAINT `FK_AVATAR_INVENTORY_CHAR` FOREIGN KEY (`FK_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `FK_AVATAR_INVENTORY_ITEM` FOREIGN KEY (`FK_ITEM`) REFERENCES `ITEM` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

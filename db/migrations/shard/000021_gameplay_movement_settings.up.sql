CREATE TABLE `GAMEPLAY_MOVEMENT_SETTINGS` (
    `SETTING_ID` TINYINT UNSIGNED NOT NULL,
    `PLAYER_WALK_SPEED` FLOAT NOT NULL,
    `PLAYER_RUN_SPEED` FLOAT NOT NULL,
    `UTIME` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`SETTING_ID`),
    CONSTRAINT `chk_gameplay_movement_singleton` CHECK (`SETTING_ID` = 1),
    CONSTRAINT `chk_gameplay_movement_walk_positive` CHECK (`PLAYER_WALK_SPEED` > 0),
    CONSTRAINT `chk_gameplay_movement_run_positive` CHECK (`PLAYER_RUN_SPEED` > 0)
) ENGINE=InnoDB;

INSERT INTO `GAMEPLAY_MOVEMENT_SETTINGS` (`SETTING_ID`, `PLAYER_WALK_SPEED`, `PLAYER_RUN_SPEED`)
VALUES (1, 16, 150);

CREATE TABLE `TELEPORT_POINT` (
    `ID` INT UNSIGNED NOT NULL,
    `CODE_NAME` VARCHAR(128) NOT NULL,
    `NPC_REF_OBJ_ID` INT UNSIGNED NOT NULL,
    `REGION_ID` SMALLINT NOT NULL,
    `POS_X` FLOAT NOT NULL,
    `POS_Y` FLOAT NOT NULL,
    `POS_Z` FLOAT NOT NULL,
    `WORLD_ID` SMALLINT NOT NULL DEFAULT 1,
    `SERVICE` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    PRIMARY KEY (`ID`),
    KEY `IX_TELEPORT_POINT_NPC` (`NPC_REF_OBJ_ID`, `SERVICE`)
);

CREATE TABLE `TELEPORT_LINK` (
    `OWNER_TELEPORT_ID` INT UNSIGNED NOT NULL,
    `TARGET_TELEPORT_ID` INT UNSIGNED NOT NULL,
    `FEE` BIGINT UNSIGNED NOT NULL,
    `SERVICE` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    PRIMARY KEY (`OWNER_TELEPORT_ID`, `TARGET_TELEPORT_ID`),
    CONSTRAINT `FK_TELEPORT_LINK_OWNER` FOREIGN KEY (`OWNER_TELEPORT_ID`) REFERENCES `TELEPORT_POINT` (`ID`),
    CONSTRAINT `FK_TELEPORT_LINK_TARGET` FOREIGN KEY (`TARGET_TELEPORT_ID`) REFERENCES `TELEPORT_POINT` (`ID`)
);


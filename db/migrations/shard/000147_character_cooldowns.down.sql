CREATE TABLE `SRO_SHARD`.`CHAR_DIMENSION_HOLE_COOLDOWN` (
    `CHAR_ID` INT NOT NULL,
    `ITEM_REF_ID` INT UNSIGNED NOT NULL,
    `EXPIRES_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`CHAR_ID`, `ITEM_REF_ID`),
    CONSTRAINT `FK_CHAR_DIMENSION_HOLE_COOLDOWN_CHARACTER`
        FOREIGN KEY (`CHAR_ID`) REFERENCES `SRO_SHARD`.`CHAR` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_CHAR_DIMENSION_HOLE_COOLDOWN_ITEM`
        FOREIGN KEY (`ITEM_REF_ID`) REFERENCES `SRO_SHARD`.`REF_DIMENSION_HOLE` (`ITEM_REF_ID`) ON DELETE RESTRICT
);

INSERT INTO `SRO_SHARD`.`CHAR_DIMENSION_HOLE_COOLDOWN` (`CHAR_ID`, `ITEM_REF_ID`, `EXPIRES_AT`)
SELECT `CHAR_ID`, `SOURCE_ID`, `EXPIRES_AT`
FROM `SRO_SHARD`.`CHAR_COOLDOWN`
WHERE `COOLDOWN_KIND`=1;

DROP TABLE `SRO_SHARD`.`CHAR_COOLDOWN`;

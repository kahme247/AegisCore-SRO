CREATE TABLE `SRO_SHARD`.`CHAR_QUEST_NAMED_POINT` (
    `CHAR_ID` INT NOT NULL,
    `POINT_KEY` VARCHAR(64) NOT NULL,
    `BALANCE` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `UPDATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`CHAR_ID`,`POINT_KEY`),
    CONSTRAINT `FK_CHAR_QUEST_NAMED_POINT_CHAR` FOREIGN KEY (`CHAR_ID`) REFERENCES `SRO_SHARD`.`CHAR` (`id`) ON DELETE CASCADE
);

UPDATE `SRO_SHARD`.`REF_QUEST_SCRIPT_POINT_REWARD`
SET `RUNTIME_ENABLED`=1
WHERE `VARIANT_INDEX`=0 AND `REWARD_KIND`='named_point' AND `AMOUNT`>0
  AND `POINT_KEY` IN ('TEMPLE_ANUBIS','TEMPLE_HAROERIS');

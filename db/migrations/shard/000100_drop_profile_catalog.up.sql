CREATE TABLE `SRO_SHARD`.`REF_DROP_CLASS_SELECTION` (
    `FAMILY` VARCHAR(32) NOT NULL,
    `MON_LEVEL` SMALLINT UNSIGNED NOT NULL,
    `PROB_GROUP` TINYINT UNSIGNED NOT NULL,
    `PROB` DOUBLE NOT NULL,
    PRIMARY KEY (`FAMILY`,`MON_LEVEL`,`PROB_GROUP`),
    CONSTRAINT `CK_REF_DROP_CLASS_SELECTION_PROB` CHECK (`PROB` >= 0)
) ENGINE=InnoDB;

CREATE TABLE `SRO_SHARD`.`REF_DROP_ITEM_ASSIGN` (
    `SOURCE_ROW` INT UNSIGNED NOT NULL,
    `SERVICE` TINYINT UNSIGNED NOT NULL,
    `REF_ITEM_ID` INT UNSIGNED NOT NULL,
    `PROB_RELATIVE` DOUBLE NOT NULL,
    `PROB_ABSOLUTE` DOUBLE NOT NULL,
    `ASSIGNED_GROUP` SMALLINT NOT NULL,
    `DROP_COUNT` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`SOURCE_ROW`),
    KEY `IX_REF_DROP_ITEM_ASSIGN_LOOKUP` (`SERVICE`,`ASSIGNED_GROUP`,`REF_ITEM_ID`),
    CONSTRAINT `CK_REF_DROP_ITEM_ASSIGN_PROB_RELATIVE` CHECK (`PROB_RELATIVE` >= 0),
    CONSTRAINT `CK_REF_DROP_ITEM_ASSIGN_PROB_ABSOLUTE` CHECK (`PROB_ABSOLUTE` >= 0)
) ENGINE=InnoDB;

CREATE TABLE `SRO_SHARD`.`REF_DROP_OPT_LEVEL_SELECTION` (
    `OPT_LEVEL` TINYINT UNSIGNED NOT NULL,
    `PROB` DOUBLE NOT NULL,
    `REQ_ONLINE_TIME` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`OPT_LEVEL`),
    CONSTRAINT `CK_REF_DROP_OPT_LEVEL_SELECTION_PROB` CHECK (`PROB` >= 0)
) ENGINE=InnoDB;

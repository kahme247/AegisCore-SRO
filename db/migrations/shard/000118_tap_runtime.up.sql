CREATE TABLE `TAP_PERIOD` (
  `ID` bigint unsigned NOT NULL AUTO_INCREMENT,
  `NPC_REF_OBJECT_ID` int unsigned NOT NULL DEFAULT 0,
  `ENTRY_TYPE` tinyint unsigned NOT NULL,
  `FROM_MONTH` tinyint unsigned NOT NULL,
  `FROM_DAY` tinyint unsigned NOT NULL,
  `FROM_HOUR` tinyint unsigned NOT NULL,
  `FROM_MINUTE` tinyint unsigned NOT NULL,
  `TO_MONTH` tinyint unsigned NOT NULL,
  `TO_DAY` tinyint unsigned NOT NULL,
  `TO_HOUR` tinyint unsigned NOT NULL,
  `TO_MINUTE` tinyint unsigned NOT NULL,
  `TRADER_UNION_POINTS` int unsigned NOT NULL DEFAULT 0,
  `THIEF_UNION_POINTS` int unsigned NOT NULL DEFAULT 0,
  `ENABLED` tinyint(1) NOT NULL DEFAULT 1,
  `UPDATED_AT` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`ID`),
  KEY `IX_TAP_PERIOD_LOOKUP` (`ENABLED`,`NPC_REF_OBJECT_ID`,`ID`),
  CONSTRAINT `CK_TAP_PERIOD_ENTRY_TYPE` CHECK (`ENTRY_TYPE` IN (2,3)),
  CONSTRAINT `CK_TAP_PERIOD_FROM_MONTH` CHECK (`FROM_MONTH` BETWEEN 1 AND 12),
  CONSTRAINT `CK_TAP_PERIOD_TO_MONTH` CHECK (`TO_MONTH` BETWEEN 1 AND 12),
  CONSTRAINT `CK_TAP_PERIOD_FROM_DAY` CHECK (`FROM_DAY` BETWEEN 1 AND 31),
  CONSTRAINT `CK_TAP_PERIOD_TO_DAY` CHECK (`TO_DAY` BETWEEN 1 AND 31),
  CONSTRAINT `CK_TAP_PERIOD_FROM_HOUR` CHECK (`FROM_HOUR` < 24),
  CONSTRAINT `CK_TAP_PERIOD_TO_HOUR` CHECK (`TO_HOUR` < 24),
  CONSTRAINT `CK_TAP_PERIOD_FROM_MINUTE` CHECK (`FROM_MINUTE` < 60),
  CONSTRAINT `CK_TAP_PERIOD_TO_MINUTE` CHECK (`TO_MINUTE` < 60),
  CONSTRAINT `CK_TAP_PERIOD_ENABLED` CHECK (`ENABLED` IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

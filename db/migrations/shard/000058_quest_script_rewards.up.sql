CREATE TABLE `SRO_SHARD`.`REF_QUEST_SCRIPT_REWARD` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `EXPERIENCE` BIGINT UNSIGNED NOT NULL,
    `SKILL_EXPERIENCE` BIGINT UNSIGNED NOT NULL,
    `GOLD` BIGINT UNSIGNED NOT NULL,
    `ITEM_COUNT` SMALLINT UNSIGNED NOT NULL,
    `PARAMETERS` JSON NOT NULL,
    `RUNTIME_ENABLED` TINYINT(1) NOT NULL DEFAULT 0,
    `SCRIPT_SHA256` CHAR(64) NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`),
    CONSTRAINT `FK_REF_QUEST_SCRIPT_REWARD_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `CK_REF_QUEST_SCRIPT_REWARD_PARAMETERS` CHECK (JSON_VALID(`PARAMETERS`)),
    CONSTRAINT `CK_REF_QUEST_SCRIPT_REWARD_ENABLED` CHECK (`RUNTIME_ENABLED` IN (0, 1))
);

CREATE TABLE `SRO_SHARD`.`REF_QUEST_SCRIPT_REWARD_ITEM` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `ITEM_INDEX` SMALLINT UNSIGNED NOT NULL,
    `REWARD_TYPE` INT UNSIGNED NOT NULL,
    `ITEM_REF_OBJECT_ID` INT NOT NULL,
    `ITEM_CODE_NAME` VARCHAR(128) NOT NULL,
    `QUANTITY` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`, `ITEM_INDEX`),
    CONSTRAINT `FK_REF_QUEST_SCRIPT_REWARD_ITEM_REWARD`
        FOREIGN KEY (`QUEST_ID`, `VARIANT_INDEX`)
        REFERENCES `SRO_SHARD`.`REF_QUEST_SCRIPT_REWARD` (`QUEST_ID`, `VARIANT_INDEX`) ON DELETE CASCADE,
    CONSTRAINT `FK_REF_QUEST_SCRIPT_REWARD_ITEM_OBJECT`
        FOREIGN KEY (`ITEM_REF_OBJECT_ID`) REFERENCES `SRO_SHARD`.`REF_OBJ_COMMON_VSRO` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_REF_QUEST_SCRIPT_REWARD_ITEM_QUANTITY` CHECK (`QUANTITY` > 0)
);

CREATE TABLE `GUILD` (
    `ID` INT NOT NULL AUTO_INCREMENT,
    `NAME` VARCHAR(20) NOT NULL,
    `LEVEL` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    `STORAGE_CAPACITY` TINYINT UNSIGNED NOT NULL DEFAULT 150,
    `STORAGE_GOLD` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_GUILD_NAME` (`NAME`)
);

CREATE TABLE `GUILD_MEMBER` (
    `FK_GUILD` INT NOT NULL,
    `FK_CHAR` INT NOT NULL,
    `STORAGE_RIGHTS` TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (`FK_GUILD`, `FK_CHAR`),
    UNIQUE KEY `UX_GUILD_MEMBER_CHAR` (`FK_CHAR`),
    CONSTRAINT `FK_GUILD_MEMBER_GUILD`
        FOREIGN KEY (`FK_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_GUILD_MEMBER_CHAR`
        FOREIGN KEY (`FK_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE
);

CREATE TABLE `GUILD_STORAGE` (
    `FK_GUILD` INT NOT NULL,
    `SLOT` TINYINT UNSIGNED NOT NULL,
    `FK_ITEM` INT NOT NULL,
    PRIMARY KEY (`FK_GUILD`, `SLOT`),
    UNIQUE KEY `UX_GUILD_STORAGE_ITEM` (`FK_ITEM`),
    CONSTRAINT `FK_GUILD_STORAGE_GUILD`
        FOREIGN KEY (`FK_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_GUILD_STORAGE_ITEM`
        FOREIGN KEY (`FK_ITEM`) REFERENCES `ITEM` (`id`)
);

CREATE TABLE `GUILD_STORAGE_LEASE` (
    `FK_GUILD` INT NOT NULL,
    `FK_CHAR` INT NOT NULL,
    `EXPIRES_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`FK_GUILD`),
    UNIQUE KEY `UX_GUILD_STORAGE_LEASE_CHAR` (`FK_CHAR`),
    CONSTRAINT `FK_GUILD_STORAGE_LEASE_GUILD`
        FOREIGN KEY (`FK_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_GUILD_STORAGE_LEASE_CHAR`
        FOREIGN KEY (`FK_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE
);

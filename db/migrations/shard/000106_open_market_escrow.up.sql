CREATE TABLE `SRO_SHARD`.`OPEN_MARKET_LISTING` (
    `ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `SELLER_CHAR_ID` INT NOT NULL,
    `BUYER_CHAR_ID` INT NULL,
    `ITEM_ID` INT NOT NULL,
    `REF_ITEM_ID` INT NOT NULL,
    `TID_GROUP_ID` INT UNSIGNED NOT NULL,
    `QUANTITY` SMALLINT UNSIGNED NOT NULL,
    `PRICE` BIGINT UNSIGNED NOT NULL,
    `DEPOSIT` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `SELL_FEE` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `STATUS` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    `VERSION` BIGINT UNSIGNED NOT NULL DEFAULT 1,
    `REGISTER_COMMAND_KEY` VARCHAR(128) NOT NULL,
    `PURCHASE_COMMAND_KEY` VARCHAR(128) NULL,
    `RETURN_COMMAND_KEY` VARCHAR(128) NULL,
    `RETURN_SLOT` TINYINT NULL,
    `REGISTERED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `EXPIRES_AT` DATETIME(6) NOT NULL,
    `SOLD_AT` DATETIME(6) NULL,
    `SETTLED_AT` DATETIME(6) NULL,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `uq_open_market_item` (`ITEM_ID`),
    UNIQUE KEY `uq_open_market_register_command` (`REGISTER_COMMAND_KEY`),
    UNIQUE KEY `uq_open_market_purchase_command` (`PURCHASE_COMMAND_KEY`),
    UNIQUE KEY `uq_open_market_return_command` (`RETURN_COMMAND_KEY`),
    KEY `ix_open_market_search` (`STATUS`,`TID_GROUP_ID`,`REF_ITEM_ID`,`REGISTERED_AT`),
    KEY `ix_open_market_seller` (`SELLER_CHAR_ID`,`STATUS`),
    CONSTRAINT `fk_open_market_seller` FOREIGN KEY (`SELLER_CHAR_ID`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `fk_open_market_buyer` FOREIGN KEY (`BUYER_CHAR_ID`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `fk_open_market_item` FOREIGN KEY (`ITEM_ID`) REFERENCES `ITEM` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `ck_open_market_quantity` CHECK (`QUANTITY` > 0),
    CONSTRAINT `ck_open_market_price` CHECK (`PRICE` > 0),
    CONSTRAINT `ck_open_market_status` CHECK (`STATUS` BETWEEN 1 AND 5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `SRO_SHARD`.`OPEN_MARKET_RECEIVABLE` (
    `LISTING_ID` BIGINT UNSIGNED NOT NULL,
    `SELLER_CHAR_ID` INT NOT NULL,
    `AMOUNT` BIGINT UNSIGNED NOT NULL,
    `SETTLEMENT_COMMAND_KEY` VARCHAR(128) NULL,
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `SETTLED_AT` DATETIME(6) NULL,
    PRIMARY KEY (`LISTING_ID`),
    UNIQUE KEY `uq_open_market_settlement_command` (`SETTLEMENT_COMMAND_KEY`),
    KEY `ix_open_market_receivable_seller` (`SELLER_CHAR_ID`,`SETTLED_AT`),
    CONSTRAINT `fk_open_market_receivable_listing` FOREIGN KEY (`LISTING_ID`) REFERENCES `OPEN_MARKET_LISTING` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `fk_open_market_receivable_seller` FOREIGN KEY (`SELLER_CHAR_ID`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `ck_open_market_receivable_amount` CHECK (`AMOUNT` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

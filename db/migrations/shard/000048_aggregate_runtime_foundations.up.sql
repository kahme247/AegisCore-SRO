CREATE TABLE `SRO_SHARD`.`AEGIS_AGGREGATE_VERSION` (
    `AGGREGATE_KIND` VARCHAR(32) NOT NULL,
    `AGGREGATE_ID` VARCHAR(128) NOT NULL,
    `VERSION` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `UPDATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`AGGREGATE_KIND`, `AGGREGATE_ID`)
);

CREATE TABLE `SRO_SHARD`.`AEGIS_COMMAND_IDEMPOTENCY` (
    `IDEMPOTENCY_KEY` VARCHAR(128) NOT NULL,
    `COMMAND_NAME` VARCHAR(128) NOT NULL,
    `AGGREGATE_KIND` VARCHAR(32) NOT NULL,
    `AGGREGATE_ID` VARCHAR(128) NOT NULL,
    `EXPECTED_VERSION` BIGINT UNSIGNED NOT NULL,
    `STATUS` ENUM('in_progress', 'completed') NOT NULL,
    `RESULT_VERSION` BIGINT UNSIGNED NULL,
    `RESULT_PAYLOAD` LONGBLOB NULL,
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `COMPLETED_AT` DATETIME(6) NULL,
    PRIMARY KEY (`IDEMPOTENCY_KEY`),
    KEY `IX_AEGIS_COMMAND_AGGREGATE` (`AGGREGATE_KIND`, `AGGREGATE_ID`, `CREATED_AT`),
    CONSTRAINT `FK_AEGIS_COMMAND_AGGREGATE` FOREIGN KEY (`AGGREGATE_KIND`, `AGGREGATE_ID`)
        REFERENCES `AEGIS_AGGREGATE_VERSION` (`AGGREGATE_KIND`, `AGGREGATE_ID`) ON DELETE CASCADE,
    CONSTRAINT `CK_AEGIS_COMMAND_RESULT` CHECK (
        (`STATUS` = 'in_progress' AND `RESULT_VERSION` IS NULL AND `COMPLETED_AT` IS NULL)
        OR (`STATUS` = 'completed' AND `RESULT_VERSION` IS NOT NULL AND `COMPLETED_AT` IS NOT NULL)
    )
);

CREATE TABLE `SRO_SHARD`.`AEGIS_OUTBOX_MESSAGE` (
    `MESSAGE_ID` VARCHAR(128) NOT NULL,
    `AGGREGATE_KIND` VARCHAR(32) NOT NULL,
    `AGGREGATE_ID` VARCHAR(128) NOT NULL,
    `AGGREGATE_VERSION` BIGINT UNSIGNED NOT NULL,
    `TOPIC` VARCHAR(128) NOT NULL,
    `PAYLOAD` LONGBLOB NOT NULL,
    `STATUS` ENUM('pending', 'published', 'dead') NOT NULL DEFAULT 'pending',
    `ATTEMPT_COUNT` INT UNSIGNED NOT NULL DEFAULT 0,
    `NEXT_ATTEMPT_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `LAST_ERROR` VARCHAR(1024) NULL,
    `OCCURRED_AT` DATETIME(6) NOT NULL,
    `PUBLISHED_AT` DATETIME(6) NULL,
    PRIMARY KEY (`MESSAGE_ID`),
    KEY `IX_AEGIS_OUTBOX_DISPATCH` (`STATUS`, `NEXT_ATTEMPT_AT`, `OCCURRED_AT`),
    KEY `IX_AEGIS_OUTBOX_AGGREGATE` (`AGGREGATE_KIND`, `AGGREGATE_ID`, `AGGREGATE_VERSION`),
    CONSTRAINT `FK_AEGIS_OUTBOX_AGGREGATE` FOREIGN KEY (`AGGREGATE_KIND`, `AGGREGATE_ID`)
        REFERENCES `AEGIS_AGGREGATE_VERSION` (`AGGREGATE_KIND`, `AGGREGATE_ID`) ON DELETE CASCADE,
    CONSTRAINT `CK_AEGIS_OUTBOX_PUBLISHED` CHECK (
        (`STATUS` = 'published' AND `PUBLISHED_AT` IS NOT NULL)
        OR (`STATUS` <> 'published' AND `PUBLISHED_AT` IS NULL)
    )
);

CREATE TABLE `SRO_SHARD`.`REF_QUEST_DIALOG_OBJECTIVE` (
    `QUEST_ID` INT NOT NULL,
    `VARIANT_INDEX` SMALLINT UNSIGNED NOT NULL,
    `MISSION_INDEX` INT UNSIGNED NOT NULL,
    `OBJECTIVE_KEY` VARCHAR(128) NOT NULL,
    `PARAMETER_4` INT UNSIGNED NOT NULL,
    `DIALOGUE_KEY` VARCHAR(128) NOT NULL,
    `PARAMETERS` JSON NOT NULL,
    `RUNTIME_ENABLED` TINYINT(1) NOT NULL DEFAULT 0,
    `SCRIPT_SHA256` CHAR(64) NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `VARIANT_INDEX`, `MISSION_INDEX`),
    CONSTRAINT `FK_REF_QUEST_DIALOG_QUEST`
        FOREIGN KEY (`QUEST_ID`) REFERENCES `SRO_SHARD`.`REF_QUEST` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `CK_REF_QUEST_DIALOG_PARAMETERS` CHECK (JSON_VALID(`PARAMETERS`)),
    CONSTRAINT `CK_REF_QUEST_DIALOG_RUNTIME_ENABLED` CHECK (`RUNTIME_ENABLED` IN (0, 1))
);

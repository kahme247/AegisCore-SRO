CREATE TABLE `SRO_SHARD`.`ACADEMY_GRADUATION` (
    `ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `ACADEMY_ID` INT UNSIGNED NOT NULL,
    `APPRENTICE_CHAR` INT NOT NULL,
    `LEADER_CHAR` INT NOT NULL,
    `ACCUMULATED_EXP` BIGINT UNSIGNED NOT NULL,
    `LEADER_EXP_AWARD` BIGINT UNSIGNED NOT NULL,
    `ASSISTANT_EXP_AWARD` BIGINT UNSIGNED NOT NULL,
    `HONOR_AWARD` INT UNSIGNED NOT NULL,
    `COMMAND_KEY` VARCHAR(128) NOT NULL,
    `GRADUATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UQ_ACADEMY_GRADUATION_APPRENTICE` (`APPRENTICE_CHAR`),
    UNIQUE KEY `UQ_ACADEMY_GRADUATION_COMMAND` (`COMMAND_KEY`),
    KEY `IX_ACADEMY_GRADUATION_LEADER` (`LEADER_CHAR`,`GRADUATED_AT`),
    CONSTRAINT `FK_ACADEMY_GRADUATION_ACADEMY` FOREIGN KEY (`ACADEMY_ID`) REFERENCES `ACADEMY` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `FK_ACADEMY_GRADUATION_APPRENTICE` FOREIGN KEY (`APPRENTICE_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_ACADEMY_GRADUATION_LEADER` FOREIGN KEY (`LEADER_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `CK_ACADEMY_GRADUATION_HONOR` CHECK (`HONOR_AWARD` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `SRO_SHARD`.`ACADEMY_MENTOR_BUFF` (
    `ACADEMY_ID` INT UNSIGNED NOT NULL,
    `CHAR_ID` INT NOT NULL,
    `BUFF_TYPE` TINYINT UNSIGNED NOT NULL,
    `VALUE` BIGINT UNSIGNED NOT NULL,
    `STARTS_AT` DATETIME(6) NOT NULL,
    `ENDS_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`ACADEMY_ID`,`CHAR_ID`,`BUFF_TYPE`),
    KEY `IX_ACADEMY_MENTOR_BUFF_ACTIVE` (`CHAR_ID`,`ENDS_AT`),
    CONSTRAINT `FK_ACADEMY_MENTOR_BUFF_ACADEMY` FOREIGN KEY (`ACADEMY_ID`) REFERENCES `ACADEMY` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_ACADEMY_MENTOR_BUFF_CHAR` FOREIGN KEY (`CHAR_ID`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `CK_ACADEMY_MENTOR_BUFF_TYPE` CHECK (`BUFF_TYPE` BETWEEN 0 AND 1),
    CONSTRAINT `CK_ACADEMY_MENTOR_BUFF_VALUE` CHECK (`VALUE` > 0),
    CONSTRAINT `CK_ACADEMY_MENTOR_BUFF_TIME` CHECK (`ENDS_AT` > `STARTS_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

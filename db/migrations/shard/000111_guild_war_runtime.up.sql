CREATE TABLE `SRO_SHARD`.`GUILD_WAR_RUNTIME` (
    `ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `CHALLENGER_GUILD` INT NOT NULL,
    `TARGET_GUILD` INT NOT NULL,
    `CHALLENGER_MASTER` INT NOT NULL,
    `TARGET_MASTER` INT NOT NULL,
    `WAR_PERIOD_ID` INT UNSIGNED NOT NULL,
    `VICTORY_POINT_ID` TINYINT UNSIGNED NOT NULL,
    `WAGER` INT UNSIGNED NOT NULL,
    `CHALLENGER_SCORE` INT UNSIGNED NOT NULL DEFAULT 0,
    `TARGET_SCORE` INT UNSIGNED NOT NULL DEFAULT 0,
    `COMMAND_KEY` VARCHAR(128) NULL,
    `STATUS` ENUM('pending','active','rejected','ended') NOT NULL,
    `WINNER_GUILD` INT NULL,
    `REWARD_GOLD` INT UNSIGNED NULL,
    `REWARD_CLAIMED_AT` DATETIME(6) NULL,
    `SURRENDERED_GUILD` INT NULL,
    `PROPOSED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `STARTED_AT` DATETIME(6) NULL,
    `DUE_AT` DATETIME(6) NULL,
    `ENDED_AT` DATETIME(6) NULL,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UQ_GUILD_WAR_COMMAND` (`COMMAND_KEY`),
    KEY `IX_GUILD_WAR_CHALLENGER_STATUS` (`CHALLENGER_GUILD`,`STATUS`),
    KEY `IX_GUILD_WAR_TARGET_STATUS` (`TARGET_GUILD`,`STATUS`),
    KEY `IX_GUILD_WAR_TARGET_MASTER_STATUS` (`TARGET_MASTER`,`STATUS`),
    KEY `IX_GUILD_WAR_STATUS_DUE` (`STATUS`,`DUE_AT`),
    CONSTRAINT `FK_GUILD_WAR_CHALLENGER_GUILD` FOREIGN KEY (`CHALLENGER_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `FK_GUILD_WAR_TARGET_GUILD` FOREIGN KEY (`TARGET_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `FK_GUILD_WAR_CHALLENGER_MASTER` FOREIGN KEY (`CHALLENGER_MASTER`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_GUILD_WAR_TARGET_MASTER` FOREIGN KEY (`TARGET_MASTER`) REFERENCES `CHAR` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_GUILD_WAR_WINNER_GUILD` FOREIGN KEY (`WINNER_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `FK_GUILD_WAR_SURRENDERED_GUILD` FOREIGN KEY (`SURRENDERED_GUILD`) REFERENCES `GUILD` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_GUILD_WAR_DISTINCT_GUILDS` CHECK (`CHALLENGER_GUILD` <> `TARGET_GUILD`),
    CONSTRAINT `CK_GUILD_WAR_WAGER` CHECK (`WAGER` <= 500000000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `SRO_SHARD`.`REF_GAME_WORLD` (
    `WORLD_ID` SMALLINT UNSIGNED NOT NULL,
    `CODE_NAME` VARCHAR(128) NOT NULL,
    `WORLD_TYPE` TINYINT UNSIGNED NOT NULL,
    `MAX_INSTANCE_COUNT` SMALLINT UNSIGNED NOT NULL,
    `MAX_USER_COUNT` SMALLINT UNSIGNED NOT NULL,
    `CONFIG_GROUP_CODE_NAME` VARCHAR(128) NOT NULL,
    PRIMARY KEY (`WORLD_ID`),
    UNIQUE KEY `UQ_REF_GAME_WORLD_CODE` (`CODE_NAME`),
    CONSTRAINT `CK_REF_GAME_WORLD_INSTANCE_COUNT` CHECK (`MAX_INSTANCE_COUNT` > 0)
);

CREATE TABLE `SRO_SHARD`.`REF_QUEST_INSTANCE_WORLD_MAP` (
    `QUEST_ID` INT NOT NULL,
    `STAGE_INDEX` TINYINT UNSIGNED NOT NULL,
    `WORLD_ID` SMALLINT UNSIGNED NOT NULL,
    PRIMARY KEY (`QUEST_ID`, `STAGE_INDEX`),
    UNIQUE KEY `UQ_REF_QUEST_INSTANCE_WORLD` (`QUEST_ID`, `WORLD_ID`),
    CONSTRAINT `FK_REF_QUEST_INSTANCE_WORLD`
        FOREIGN KEY (`WORLD_ID`) REFERENCES `SRO_SHARD`.`REF_GAME_WORLD` (`WORLD_ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_REF_QUEST_INSTANCE_STAGE` CHECK (`STAGE_INDEX` > 0)
);

CREATE TABLE `SRO_SHARD`.`QUEST_INSTANCE_SCOPE_RESERVATION` (
    `WORLD_ID` SMALLINT UNSIGNED NOT NULL,
    `LAYER_ID` SMALLINT UNSIGNED NOT NULL,
    `QUEST_ID` INT NOT NULL,
    `DUNGEON_KEY_ID` INT UNSIGNED NOT NULL,
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`WORLD_ID`, `LAYER_ID`),
    UNIQUE KEY `UQ_QUEST_INSTANCE_DUNGEON_KEY` (`DUNGEON_KEY_ID`),
    CONSTRAINT `FK_QUEST_INSTANCE_SCOPE_WORLD`
        FOREIGN KEY (`WORLD_ID`) REFERENCES `SRO_SHARD`.`REF_GAME_WORLD` (`WORLD_ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_QUEST_INSTANCE_SCOPE_LAYER` CHECK (`LAYER_ID` > 0 AND `LAYER_ID` < 65535)
);


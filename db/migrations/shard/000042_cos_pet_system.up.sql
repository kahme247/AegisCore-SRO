CREATE TABLE `CHAR_COS` (
    `ID` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `OWNER_CHAR_ID` INT NOT NULL,
    `REF_OBJECT_ID` INT NOT NULL,
    `KIND` TINYINT UNSIGNED NOT NULL,
    `INVENTORY_SLOT` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `MP` INT NOT NULL DEFAULT 0,
    `KEEPER_NPC` INT NOT NULL DEFAULT 0,
    `STATE` TINYINT UNSIGNED NOT NULL DEFAULT 3,
    `NAME` VARCHAR(16) NOT NULL DEFAULT '',
    `NAME_NORMALIZED` VARCHAR(16) GENERATED ALWAYS AS (NULLIF(LOWER(TRIM(`NAME`)), '')) STORED,
    `LEVEL` TINYINT UNSIGNED NOT NULL DEFAULT 1,
    `EXPERIENCE` BIGINT NOT NULL DEFAULT 0,
    `HEALTH` INT NOT NULL DEFAULT 1,
    `MAX_HEALTH` INT NOT NULL DEFAULT 1,
    `HGP` SMALLINT UNSIGNED NOT NULL DEFAULT 10000,
    `SATIETY` INT NOT NULL DEFAULT 0,
    `SETTINGS` INT UNSIGNED NOT NULL DEFAULT 0,
    `RENT_ENDS_AT` DATETIME(6) NULL,
    `UPDATED_AT` TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`ID`),
    KEY `IX_CHAR_COS_OWNER` (`OWNER_CHAR_ID`),
    KEY `IX_CHAR_COS_REFERENCE` (`REF_OBJECT_ID`),
    UNIQUE KEY `UX_CHAR_COS_NAME_NORMALIZED` (`NAME_NORMALIZED`),
    CONSTRAINT `CK_CHAR_COS_KIND` CHECK (`KIND` BETWEEN 1 AND 9),
    CONSTRAINT `CK_CHAR_COS_LEVEL` CHECK (`LEVEL` > 0),
    CONSTRAINT `CK_CHAR_COS_HEALTH` CHECK (`HEALTH` >= 0 AND `MAX_HEALTH` > 0 AND `HEALTH` <= `MAX_HEALTH`),
    CONSTRAINT `FK_CHAR_COS_OWNER` FOREIGN KEY (`OWNER_CHAR_ID`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `FK_CHAR_COS_REFERENCE` FOREIGN KEY (`REF_OBJECT_ID`) REFERENCES `CHAR_REF_DATA` (`RefObjID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `COS_INVENTORY` (
    `COS_ID` INT UNSIGNED NOT NULL,
    `SLOT` TINYINT UNSIGNED NOT NULL,
    `FK_ITEM` INT NOT NULL,
    PRIMARY KEY (`COS_ID`, `SLOT`),
    UNIQUE KEY `UX_COS_INVENTORY_ITEM` (`FK_ITEM`),
    CONSTRAINT `FK_COS_INVENTORY_COS` FOREIGN KEY (`COS_ID`) REFERENCES `CHAR_COS` (`ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_COS_INVENTORY_ITEM` FOREIGN KEY (`FK_ITEM`) REFERENCES `ITEM` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

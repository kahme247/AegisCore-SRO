CREATE TABLE `SRO_SHARD`.`AEGIS_SCHEDULE_DEFINITION` (
    `SCHEDULE_ID` VARCHAR(128) NOT NULL,
    `NAME` VARCHAR(128) NOT NULL,
    `HANDLER` VARCHAR(128) NOT NULL,
    `PAYLOAD` LONGBLOB NOT NULL,
    `RECURRENCE` ENUM('one_time', 'daily', 'weekly') NOT NULL,
    `PHASE` ENUM('warning', 'start', 'update', 'finish') NOT NULL,
    `SCOPE` ENUM('shard', 'all_shards') NOT NULL,
    `SHARD_ID` SMALLINT UNSIGNED NULL,
    `TIMEZONE` VARCHAR(64) NOT NULL,
    `ACTIVE_FROM` DATE NULL,
    `ACTIVE_UNTIL` DATE NULL,
    `RUN_AT` DATETIME(6) NULL,
    `SECOND_OF_DAY` INT UNSIGNED NULL,
    `INTERVAL_VALUE` SMALLINT UNSIGNED NULL,
    `WEEKDAY_MASK` TINYINT UNSIGNED NULL,
    `MISFIRE_POLICY` ENUM('skip', 'run_once') NOT NULL,
    `ENABLED` BOOLEAN NOT NULL DEFAULT FALSE,
    `VERSION` BIGINT UNSIGNED NOT NULL DEFAULT 1,
    `NEXT_RUN_AT` DATETIME(6) NULL,
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `UPDATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`SCHEDULE_ID`),
    KEY `IX_AEGIS_SCHEDULE_DUE` (`ENABLED`, `NEXT_RUN_AT`, `SCHEDULE_ID`),
    CONSTRAINT `CK_AEGIS_SCHEDULE_SCOPE` CHECK (
        (`SCOPE` = 'shard' AND `SHARD_ID` IS NOT NULL AND `SHARD_ID` > 0)
        OR (`SCOPE` = 'all_shards' AND `SHARD_ID` IS NULL)
    ),
    CONSTRAINT `CK_AEGIS_SCHEDULE_RECURRENCE` CHECK (
        (`RECURRENCE` = 'one_time' AND `RUN_AT` IS NOT NULL AND `ACTIVE_FROM` IS NULL AND `ACTIVE_UNTIL` IS NULL AND `SECOND_OF_DAY` IS NULL AND `INTERVAL_VALUE` IS NULL AND `WEEKDAY_MASK` IS NULL)
        OR (`RECURRENCE` = 'daily' AND `RUN_AT` IS NULL AND `ACTIVE_FROM` IS NOT NULL AND `ACTIVE_UNTIL` IS NOT NULL AND `SECOND_OF_DAY` IS NOT NULL AND `SECOND_OF_DAY` < 86400 AND `INTERVAL_VALUE` > 0 AND `WEEKDAY_MASK` IS NULL)
        OR (`RECURRENCE` = 'weekly' AND `RUN_AT` IS NULL AND `ACTIVE_FROM` IS NOT NULL AND `ACTIVE_UNTIL` IS NOT NULL AND `SECOND_OF_DAY` IS NOT NULL AND `SECOND_OF_DAY` < 86400 AND `INTERVAL_VALUE` > 0 AND `WEEKDAY_MASK` BETWEEN 1 AND 127)
    ),
    CONSTRAINT `CK_AEGIS_SCHEDULE_RANGE` CHECK (`ACTIVE_UNTIL` IS NULL OR `ACTIVE_FROM` <= `ACTIVE_UNTIL`),
    CONSTRAINT `CK_AEGIS_SCHEDULE_PAYLOAD` CHECK (JSON_VALID(`PAYLOAD`))
);

CREATE TABLE `SRO_SHARD`.`AEGIS_SCHEDULE_RUN` (
    `RUN_ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `FK_SCHEDULE` VARCHAR(128) NOT NULL,
    `SCHEDULE_VERSION` BIGINT UNSIGNED NOT NULL,
    `SCHEDULED_FOR` DATETIME(6) NOT NULL,
    `HANDLER` VARCHAR(128) NOT NULL,
    `PAYLOAD` LONGBLOB NOT NULL,
    `PHASE` ENUM('warning', 'start', 'update', 'finish') NOT NULL,
    `SCOPE` ENUM('shard', 'all_shards') NOT NULL,
    `SHARD_ID` SMALLINT UNSIGNED NULL,
    `STATUS` ENUM('pending', 'processing', 'succeeded', 'failed', 'skipped', 'dead') NOT NULL DEFAULT 'pending',
    `ATTEMPT_COUNT` INT UNSIGNED NOT NULL DEFAULT 0,
    `NEXT_ATTEMPT_AT` DATETIME(6) NOT NULL,
    `LEASE_OWNER` VARCHAR(128) NULL,
    `LEASE_UNTIL` DATETIME(6) NULL,
    `LAST_ERROR` VARCHAR(1024) NULL,
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `STARTED_AT` DATETIME(6) NULL,
    `FINISHED_AT` DATETIME(6) NULL,
    PRIMARY KEY (`RUN_ID`),
    UNIQUE KEY `UX_AEGIS_SCHEDULE_RUN_OCCURRENCE` (`FK_SCHEDULE`, `SCHEDULED_FOR`),
    KEY `IX_AEGIS_SCHEDULE_RUN_DUE` (`STATUS`, `NEXT_ATTEMPT_AT`, `SCHEDULED_FOR`),
    CONSTRAINT `FK_AEGIS_SCHEDULE_RUN_DEFINITION` FOREIGN KEY (`FK_SCHEDULE`)
        REFERENCES `AEGIS_SCHEDULE_DEFINITION` (`SCHEDULE_ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_AEGIS_SCHEDULE_RUN_SCOPE` CHECK (
        (`SCOPE` = 'shard' AND `SHARD_ID` IS NOT NULL AND `SHARD_ID` > 0)
        OR (`SCOPE` = 'all_shards' AND `SHARD_ID` IS NULL)
    ),
    CONSTRAINT `CK_AEGIS_SCHEDULE_RUN_STATE` CHECK (
        (`STATUS` = 'pending' AND `LEASE_OWNER` IS NULL AND `LEASE_UNTIL` IS NULL AND `FINISHED_AT` IS NULL)
        OR (`STATUS` = 'processing' AND `LEASE_OWNER` IS NOT NULL AND `LEASE_UNTIL` IS NOT NULL AND `STARTED_AT` IS NOT NULL AND `FINISHED_AT` IS NULL)
        OR (`STATUS` IN ('succeeded', 'failed', 'skipped', 'dead') AND `LEASE_OWNER` IS NULL AND `LEASE_UNTIL` IS NULL AND `FINISHED_AT` IS NOT NULL)
    ),
    CONSTRAINT `CK_AEGIS_SCHEDULE_RUN_PAYLOAD` CHECK (JSON_VALID(`PAYLOAD`))
);

CREATE TABLE `SRO_SHARD`.`CHAR_QUEST_INSTANCE_WORLD` (
    `CHAR_ID` INT NOT NULL,
    `DUNGEON_KEY_ID` INT UNSIGNED NOT NULL,
    `WORLD_ID` SMALLINT UNSIGNED NOT NULL,
    `LAYER_ID` SMALLINT UNSIGNED NOT NULL,
    `OPENED_AT` DATETIME(6) NOT NULL,
    `REGION_ID` SMALLINT NOT NULL,
    `POS_X` FLOAT NOT NULL,
    `POS_Y` FLOAT NOT NULL,
    `POS_Z` FLOAT NOT NULL,
    `IS_ACTIVATED` BOOLEAN NOT NULL DEFAULT FALSE,
    `ENTER_COUNT` INT UNSIGNED NOT NULL DEFAULT 0,
    `LAST_ENTER_AT` DATETIME(6) NULL,
    PRIMARY KEY (`CHAR_ID`, `WORLD_ID`),
    UNIQUE KEY `UQ_CHAR_QUEST_INSTANCE_KEY` (`CHAR_ID`, `DUNGEON_KEY_ID`),
    KEY `IX_CHAR_QUEST_INSTANCE_SCOPE` (`WORLD_ID`, `LAYER_ID`),
    CONSTRAINT `FK_CHAR_QUEST_INSTANCE_CHAR`
        FOREIGN KEY (`CHAR_ID`) REFERENCES `SRO_SHARD`.`CHAR` (`id`) ON DELETE CASCADE,
    CONSTRAINT `CK_CHAR_QUEST_INSTANCE_WORLD` CHECK (`WORLD_ID` > 0 AND `WORLD_ID` < 65535),
    CONSTRAINT `CK_CHAR_QUEST_INSTANCE_LAYER` CHECK (`LAYER_ID` > 0 AND `LAYER_ID` < 65535)
);

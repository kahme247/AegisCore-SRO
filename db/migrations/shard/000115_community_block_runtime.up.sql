CREATE TABLE `COMMUNITY_BLOCK` (
  `BLOCKER_CHAR` int NOT NULL,
  `BLOCKED_CHAR` int NOT NULL,
  `CREATED_AT` datetime(6) NOT NULL,
  PRIMARY KEY (`BLOCKER_CHAR`,`BLOCKED_CHAR`),
  KEY `IX_COMMUNITY_BLOCK_BLOCKED` (`BLOCKED_CHAR`,`BLOCKER_CHAR`),
  CONSTRAINT `CK_COMMUNITY_BLOCK_DISTINCT` CHECK (`BLOCKER_CHAR` <> `BLOCKED_CHAR`),
  CONSTRAINT `FK_COMMUNITY_BLOCK_BLOCKER` FOREIGN KEY (`BLOCKER_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_COMMUNITY_BLOCK_BLOCKED` FOREIGN KEY (`BLOCKED_CHAR`) REFERENCES `CHAR` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Mirror the verified lobby predicates: degree-one, level-one Chinese equipment
-- in the four request slots. Catalog gender 2 denotes a gender-neutral weapon.
INSERT INTO `CHARACTER_CREATION_STARTER_ITEM`
    (`MODEL_ID`, `REF_ITEM_ID`, `SLOT`, `WEAPON_SELECTION`)
SELECT
    model.`MODEL_ID`,
    item.`ItemID`,
    CASE
        WHEN item.`TypeID_3` = 6 THEN 6
        WHEN item.`TypeID_4` = 3 THEN 1
        WHEN item.`TypeID_4` = 4 THEN 4
        ELSE 5
    END,
    item.`TypeID_3` = 6
FROM `CHARACTER_CREATION_MODEL` AS model
JOIN `ITEMDATA` AS item
  ON item.`CashItem` = 0
 AND item.`TypeID_1` = 3
 AND item.`TypeID_2` = 1
 AND item.`ItemClass` = 1
 AND item.`Req_Level_1` <= 1
 AND (
      (model.`RACE` = 1 AND item.`Req_Level_Type_1` = 1)
   OR (model.`RACE` = 2 AND item.`Req_Level_Type_1` IN (1, 513, 514))
 )
 AND (item.`Required_Gender` IN (0, 2) OR item.`Required_Gender` = model.`GENDER`)
 AND (
      (model.`RACE` = 1 AND (
           (item.`TypeID_3` = 6 AND item.`TypeID_4` BETWEEN 2 AND 6)
        OR (item.`TypeID_3` IN (1, 2, 3) AND item.`TypeID_4` IN (3, 4, 6))
      ))
   OR (model.`RACE` = 2 AND (
           (item.`TypeID_3` = 6 AND item.`TypeID_4` BETWEEN 7 AND 15)
        OR (item.`TypeID_3` IN (9, 10, 11) AND item.`TypeID_4` IN (3, 4, 6))
      ))
 );

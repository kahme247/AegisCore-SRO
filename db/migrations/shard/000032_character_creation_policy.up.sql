CREATE TABLE `CHARACTER_CREATION_MODEL` (
    `MODEL_ID` INT NOT NULL,
    `RACE` TINYINT UNSIGNED NOT NULL COMMENT '1=Chinese, 2=European',
    `GENDER` TINYINT UNSIGNED NOT NULL COMMENT '0=female, 1=male',
    `INITIAL_LEVEL` SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    `INITIAL_EXP` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `INITIAL_SKILL_EXP` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `INITIAL_STRENGTH` SMALLINT UNSIGNED NOT NULL DEFAULT 20,
    `INITIAL_INTELLECT` SMALLINT UNSIGNED NOT NULL DEFAULT 20,
    `INITIAL_STAT_POINTS` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `INITIAL_HP` INT UNSIGNED NOT NULL DEFAULT 200,
    `INITIAL_MP` INT UNSIGNED NOT NULL DEFAULT 200,
    `INITIAL_POS_X` FLOAT NOT NULL,
    `INITIAL_POS_Y` FLOAT NOT NULL,
    `INITIAL_POS_Z` FLOAT NOT NULL,
    `INITIAL_REGION_ID` INT NOT NULL,
    `INITIAL_RETURN_TELEPORT_ID` INT UNSIGNED NOT NULL,
    `INITIAL_INVENTORY_SIZE` SMALLINT UNSIGNED NOT NULL DEFAULT 45,
    PRIMARY KEY (`MODEL_ID`),
    KEY `IX_CHARACTER_CREATION_MODEL_RACE_GENDER` (`RACE`, `GENDER`),
    KEY `IX_CHARACTER_CREATION_MODEL_REGION` (`INITIAL_REGION_ID`),
    KEY `IX_CHARACTER_CREATION_MODEL_RETURN_TELEPORT` (`INITIAL_RETURN_TELEPORT_ID`),
    CONSTRAINT `FK_CHARACTER_CREATION_MODEL_REF` FOREIGN KEY (`MODEL_ID`) REFERENCES `CHAR_REF_DATA` (`RefObjID`),
    CONSTRAINT `FK_CHARACTER_CREATION_MODEL_REGION` FOREIGN KEY (`INITIAL_REGION_ID`) REFERENCES `REGION_REFERENCE` (`wRegionID`),
    CONSTRAINT `FK_CHARACTER_CREATION_MODEL_RETURN_TELEPORT` FOREIGN KEY (`INITIAL_RETURN_TELEPORT_ID`) REFERENCES `TELEPORT_POINT` (`ID`),
    CONSTRAINT `CK_CHARACTER_CREATION_MODEL_RACE` CHECK (`RACE` IN (1, 2)),
    CONSTRAINT `CK_CHARACTER_CREATION_MODEL_GENDER` CHECK (`GENDER` IN (0, 1)),
    CONSTRAINT `CK_CHARACTER_CREATION_MODEL_INITIAL_VALUES` CHECK (`INITIAL_LEVEL` > 0 AND `INITIAL_HP` > 0 AND `INITIAL_MP` > 0 AND `INITIAL_INVENTORY_SIZE` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;


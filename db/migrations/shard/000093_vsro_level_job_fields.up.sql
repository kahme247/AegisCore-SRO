ALTER TABLE `SRO_SHARD`.`REF_LEVEL_DATA`
    ADD COLUMN `JOB_ACTIVITY_FACTOR` BIGINT UNSIGNED NOT NULL DEFAULT 0 AFTER `UNKNOWN_2`;

UPDATE `SRO_SHARD`.`REF_LEVEL_DATA`
SET `JOB_ACTIVITY_FACTOR`=CAST(JSON_UNQUOTE(JSON_EXTRACT(`RAW_FIELDS`,'$[5]')) AS UNSIGNED),
    `REQUIRED_JOB_EXPERIENCE`=CAST(JSON_UNQUOTE(JSON_EXTRACT(`RAW_FIELDS`,'$[6]')) AS SIGNED),
    `REQUIRED_JOB_EXPERIENCE_2`=CAST(JSON_UNQUOTE(JSON_EXTRACT(`RAW_FIELDS`,'$[7]')) AS SIGNED),
    `REQUIRED_JOB_EXPERIENCE_3`=CAST(JSON_UNQUOTE(JSON_EXTRACT(`RAW_FIELDS`,'$[8]')) AS SIGNED)
WHERE JSON_LENGTH(`RAW_FIELDS`) >= 9;

UPDATE `SRO_SHARD`.`REF_JOB_LEVEL_EXPERIENCE` target
JOIN `SRO_SHARD`.`REF_LEVEL_DATA` source ON source.`LEVEL`=target.`JOB_LEVEL`
SET target.`REQUIRED_EXPERIENCE`=source.`REQUIRED_JOB_EXPERIENCE`
WHERE source.`LEVEL` BETWEEN 1 AND 7 AND source.`REQUIRED_JOB_EXPERIENCE` > 0;

ALTER TABLE `SRO_SHARD`.`REF_LEVEL_DATA`
    ADD CONSTRAINT `CK_REF_LEVEL_JOB_ACTIVITY_FACTOR` CHECK (`JOB_ACTIVITY_FACTOR` > 0);

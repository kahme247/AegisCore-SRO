CREATE TABLE `PATCH_MODULE_STATE` (
    `DIVISION_ID` TINYINT UNSIGNED NOT NULL,
    `CONTENT_ID` TINYINT UNSIGNED NOT NULL,
    `MODULE_ID` TINYINT UNSIGNED NOT NULL,
    `MODULE_NAME` VARCHAR(64) NOT NULL,
    `ACTIVE_VERSION` INT UNSIGNED NOT NULL,
    `MIN_PATCH_VERSION` INT UNSIGNED NOT NULL,
    `UPDATED_AT` TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`DIVISION_ID`,`CONTENT_ID`,`MODULE_ID`,`MODULE_NAME`),
    UNIQUE KEY `UX_PATCH_MODULE_STATE_CLIENT` (`CONTENT_ID`,`MODULE_NAME`),
    CONSTRAINT `CK_PATCH_MODULE_STATE_FLOOR` CHECK (`MIN_PATCH_VERSION` <= `ACTIVE_VERSION`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `PATCH_RELEASE` (
    `ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `DIVISION_ID` TINYINT UNSIGNED NOT NULL,
    `CONTENT_ID` TINYINT UNSIGNED NOT NULL,
    `MODULE_ID` TINYINT UNSIGNED NOT NULL,
    `MODULE_NAME` VARCHAR(64) NOT NULL,
    `BASE_VERSION` INT UNSIGNED NOT NULL,
    `VERSION` INT UNSIGNED NOT NULL,
    `DISPLAY_VERSION` VARCHAR(32) NOT NULL DEFAULT '',
    `DESCRIPTION` VARCHAR(255) NOT NULL DEFAULT '',
    `STATUS` VARCHAR(16) NOT NULL DEFAULT 'draft',
    `CREATED_AT` TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `VALIDATED_AT` TIMESTAMP(6) NULL,
    `PUBLISHED_AT` TIMESTAMP(6) NULL,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_PATCH_RELEASE_TUPLE_VERSION` (`DIVISION_ID`,`CONTENT_ID`,`MODULE_ID`,`MODULE_NAME`,`VERSION`),
    KEY `IX_PATCH_RELEASE_LOOKUP` (`CONTENT_ID`,`MODULE_NAME`,`STATUS`,`VERSION`),
    CONSTRAINT `CK_PATCH_RELEASE_INCREMENT` CHECK (`VERSION` = `BASE_VERSION` + 1),
    CONSTRAINT `CK_PATCH_RELEASE_STATUS` CHECK (`STATUS` IN ('draft','testing','published','retired')),
    CONSTRAINT `FK_PATCH_RELEASE_MODULE` FOREIGN KEY (`DIVISION_ID`,`CONTENT_ID`,`MODULE_ID`,`MODULE_NAME`)
        REFERENCES `PATCH_MODULE_STATE` (`DIVISION_ID`,`CONTENT_ID`,`MODULE_ID`,`MODULE_NAME`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `PATCH_RELEASE_FILE` (
    `ID` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `FK_RELEASE` BIGINT UNSIGNED NOT NULL,
    `ORDINAL` SMALLINT UNSIGNED NOT NULL,
    `FILENAME` VARCHAR(255) NOT NULL,
    `PATH` VARCHAR(512) NOT NULL DEFAULT '',
    `PREPARED_SIZE` BIGINT UNSIGNED NOT NULL,
    `IMPORT_TO_PK2` TINYINT(1) NOT NULL,
    `STORAGE_KEY` VARCHAR(768) NOT NULL,
    `PREPARED_SHA256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `TARGET_SIZE` BIGINT UNSIGNED NOT NULL,
    `TARGET_SHA256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `VALID` TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_PATCH_RELEASE_FILE_ORDINAL` (`FK_RELEASE`,`ORDINAL`),
    CONSTRAINT `FK_PATCH_RELEASE_FILE_RELEASE` FOREIGN KEY (`FK_RELEASE`) REFERENCES `PATCH_RELEASE` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `CK_PATCH_RELEASE_FILE_IMPORT` CHECK (`IMPORT_TO_PK2` IN (0, 1)),
    CONSTRAINT `CK_PATCH_RELEASE_FILE_VALID` CHECK (`VALID` IN (0, 1)),
    CONSTRAINT `CK_PATCH_RELEASE_FILE_PREPARED_HASH` CHECK (`PREPARED_SHA256` REGEXP '^[0-9a-f]{64}$'),
    CONSTRAINT `CK_PATCH_RELEASE_FILE_TARGET_HASH` CHECK (`TARGET_SHA256` REGEXP '^[0-9a-f]{64}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `PATCH_DOWNLOAD_SERVER` (
    `ID` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `PUBLIC_HOST` VARCHAR(255) NOT NULL,
    `PUBLIC_PORT` SMALLINT UNSIGNED NOT NULL,
    `ENABLED` TINYINT(1) NOT NULL DEFAULT 0,
    `WEIGHT` SMALLINT UNSIGNED NOT NULL DEFAULT 100,
    `UPDATED_AT` TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_PATCH_DOWNLOAD_SERVER_ENDPOINT` (`PUBLIC_HOST`,`PUBLIC_PORT`),
    CONSTRAINT `CK_PATCH_DOWNLOAD_SERVER_ENABLED` CHECK (`ENABLED` IN (0, 1)),
    CONSTRAINT `CK_PATCH_DOWNLOAD_SERVER_PORT` CHECK (`PUBLIC_PORT` > 0),
    CONSTRAINT `CK_PATCH_DOWNLOAD_SERVER_WEIGHT` CHECK (`WEIGHT` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
